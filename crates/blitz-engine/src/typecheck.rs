//! Static type checker for TypeScript/JavaScript programs.
//!
//! This module performs compile-time type checking before bytecode generation.
//! It validates:
//! - Variable declarations and assignments
//! - Function parameter and return types
//! - Binary and unary operations
//! - Control flow constructs
//! - Object and array literals
//!
//! The checker consumes Oxc's `oast::Program` directly (no ESTree/owned-ast
//! round-trip). It provides a lightweight conservative `Type` model used for
//! soft-layer and prelude validation.

use crate::errors::TypeCheckerError;
use oxc_ast::ast as oast;

// Reintroduce a compact Type enum here (previously in oxc_typecheck) so other
// modules can reference `crate::typecheck::Type` after removing the duplicate
// module. Keep it conservative and compatible with existing usage.
use std::collections::{HashMap, HashSet};

/// Lightweight, conservative representation of types used by the checker.
///
/// This `Type` enum is not a full TypeScript type system; it models the
/// subset of types that the VM and the soft layer (blitzlib) need for
/// basic static checks. It is intentionally small and pragmatic:
///
/// - Primitive kinds: `Number`, `String`, `Boolean`, `Null`, `Undefined`, `Void`.
/// - Top-like/unknown markers: `Any`, `Unknown`
/// - Compound shapes: `Array`, `Function`, `Object`
/// - `Builtin` enumerates host-provided runtime categories (see `BuiltinType`)
/// - `TypeReference` names a type that should be resolved via lexical scope.
/// - `Union` models simple union types (no type algebra beyond membership).
///
/// Notes on usage and semantics:
/// - `Type::Array(inner)` denotes a homogeneous array of `inner` type.
/// - `Type::Function(params, ret)` uses a `Vec<Type>` for parameters and a boxed return type.
///   We treat empty parameter lists as a convention to mean "variadic" (e.g. `console.log` in the prelude).
/// - `Type::Object` performs shallow structural checks in `assignable`:
///   every property declared in the expected object must exist and be assignable.
/// - `TypeReference` is a name-only reference resolved through the checker type table.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Type {
  /// Bottom type used for impossible branches.
  Never,
  /// Numeric values (JS `number`).
  Number,
  /// String values (JS `string`).
  String,
  /// Boolean values (JS `boolean`).
  Boolean,
  /// The `null` literal/marker.
  Null,
  /// The JavaScript `undefined` value and TypeScript `undefined` type.
  Undefined,
  /// Represents `void`/no-value (used for function returns and some host APIs).
  Void,
  /// A deliberately permissive top type. Used when the caller chooses to be lax.
  Any,
  /// An unknown type returned from incomplete inference; treated separately from `Any`.
  Unknown,
  /// Homogeneous array type.
  Array(Box<Type>),
  /// Fixed-position tuple elements.
  Tuple(Vec<Type>),
  /// Variadic tuple tail pattern.
  Rest(Box<Type>),
  /// Function type with parameter types and return type.
  Function(Vec<Type>, Box<Type>),
  /// Object with named properties and their types.
  Object(HashMap<String, Type>),
  /// A builtin runtime category.
  Builtin(BuiltinType),
  /// A reference to a named type that should be looked up in the current scope.
  TypeReference {
    /// Name of the referred type.
    name: String,
    /// Type arguments supplied to a generic definition.
    arguments: Vec<Type>,
  },
  /// Union of other `Type` variants (simple, flat unions).
  Union(Vec<Type>),
  /// Intersection of other types.
  Intersection(Vec<Type>),
  /// A string, number, or boolean literal type.
  Literal(LiteralType),
  /// A conditional type expression.
  Conditional {
    /// Type being tested.
    check: Box<Type>,
    /// Constraint on the tested type.
    extends: Box<Type>,
    /// Result when assignable.
    true_type: Box<Type>,
    /// Result when not assignable.
    false_type: Box<Type>,
    /// Naked type parameter used for distributive conditional evaluation.
    distributive_parameter: Option<String>,
  },
  /// Property keys of another type.
  KeyOf(Box<Type>),
  /// Property lookup in the type domain.
  IndexedAccess {
    /// Object or tuple being indexed.
    object: Box<Type>,
    /// Key or union of keys.
    index: Box<Type>,
  },
  /// Binding introduced by `infer` in a conditional constraint.
  Infer(String),
  /// Object type generated by iterating a union of property keys.
  Mapped {
    /// Per-property type parameter.
    parameter: String,
    /// Union of keys to iterate.
    constraint: Box<Type>,
    /// Value type generated for each key.
    value: Box<Type>,
  },
  /// Compile-time string interpolation.
  TemplateLiteral {
    /// Static segments surrounding substitutions.
    quasis: Vec<String>,
    /// Types interpolated between segments.
    substitutions: Vec<Type>,
  },
}

/// Exact primitive values represented by literal types.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub enum LiteralType {
  /// Exact string value.
  String(String),
  /// Exact IEEE-754 number bits.
  Number(u64),
  /// Exact boolean value.
  Boolean(bool),
}

#[derive(Debug, Clone)]
struct TypeParameter {
  name: String,
  constraint: Option<Type>,
  default: Option<Type>,
}

#[derive(Debug, Clone)]
struct TypeDefinition {
  parameters: Vec<TypeParameter>,
  body: Type,
}

#[derive(Debug, Clone, PartialEq, Eq, Hash)]
/// Enumeration of runtime built-in type categories that the checker recognizes.
///
/// These correspond to the engine's coarse-grained runtime kinds. The
/// typechecker uses `BuiltinType` when representing host-provided values
/// and to format diagnostics that mention runtime types.
///
/// Note: this is not an extensible tag-scheme; if you add runtime categories
/// you should update both this enum and call sites that map runtime values to
/// builtins.
pub enum BuiltinType {
  /// Represents `undefined` values.
  Undefined,
  /// Represents `null`.
  Null,
  /// Boolean runtime kind.
  Boolean,
  /// Numeric runtime kind.
  Number,
  /// String runtime kind.
  String,
  /// Symbol runtime kind.
  Symbol,
  /// BigInt runtime kind.
  BigInt,
  /// Generic object runtime kind.
  Object,
  /// Function runtime kind.
  Function,
  /// Array runtime kind.
  Array,
}

type Scope = HashMap<String, Type>;
type TypeEnvironment = HashMap<String, Type>;

#[derive(Debug, Clone, Default)]
struct ModuleType {
  values: HashMap<String, Type>,
  types: HashMap<String, TypeDefinition>,
  namespaces: HashMap<String, ModuleType>,
}

const TYPE_EVALUATION_LIMIT: usize = 128;

thread_local! {
    static STRICT_OVERRIDE: std::cell::RefCell<Option<bool>> = const { std::cell::RefCell::new(None) };
}

/// Return whether strict mode is currently enabled.
///
/// The checker consults this flag when deciding whether unannotated parameters
/// should produce implicit-`any` diagnostics. The effective strictness is
/// determined by, in order:
/// 1. The test-only override set via `set_strict_override(Some(bool))`.
/// 2. The environment variable `TSBLITZ_STRICT` (non-zero means enabled).
/// 3. Defaults to disabled when the environment variable is not set.
fn strict_mode() -> bool {
  if let Some(v) = STRICT_OVERRIDE.with(|m| *m.borrow()) {
    return v;
  }
  std::env::var("TSBLITZ_STRICT").is_ok_and(|v| v != "0")
}

/// Override strict-mode behavior for type checking.
///
/// Passing `Some(true)` or `Some(false)` forces strict mode on or off.
/// Passing `None` clears the override and restores environment-driven behavior.
///
/// # Panics
/// Panics if the override mutex is poisoned.
pub fn set_strict_override(v: Option<bool>) {
  STRICT_OVERRIDE.with(|m| {
    *m.borrow_mut() = v;
  });
}

/// Return the current thread-local strict override, if any.
pub(crate) fn strict_override() -> Option<bool> {
  STRICT_OVERRIDE.with(|m| *m.borrow())
}

/// Temporarily set the thread-local strict override while running `f`.
pub fn with_strict_override<R>(
  v: Option<bool>,
  f: impl FnOnce() -> R,
) -> R {
  struct ResetStrict(Option<bool>);

  impl Drop for ResetStrict {
    fn drop(&mut self) {
      set_strict_override(self.0);
    }
  }

  let previous = strict_override();
  set_strict_override(v);
  let _reset = ResetStrict(previous);
  f()
}

/// Run static type checking for a parsed program.
///
/// # Errors
/// Returns a `TypeCheckerError` if type checking fails.
pub fn check(program: &oast::Program<'_>) -> Result<(), TypeCheckerError> {
  check_with_declarations(program, &[])
}

/// A declaration source associated with a public virtual module.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct VirtualDeclaration {
  /// Canonical module specifier used by imports.
  pub specifier: String,
  /// TypeScript declaration source for the module.
  pub source: String,
}

/// Check a program against declarations retained by public virtual modules.
pub fn check_with_declarations(
  program: &oast::Program<'_>,
  declarations: &[VirtualDeclaration],
) -> Result<(), TypeCheckerError> {
  check_with_declarations_and_source_imports(program, declarations, &[])
}

/// Check a program against virtual declarations and imports resolved as source
/// modules by the module loader.
///
/// Source-module imports have no declaration model in this checker. They are
/// registered as `Unknown` bindings so they do not become declaration-module
/// lookups or silently acquire `Any` types. Imports whose source is neither a
/// supplied declaration nor a loader-confirmed source module remain strict
/// errors.
pub fn check_with_declarations_and_source_imports(
  program: &oast::Program<'_>,
  declarations: &[VirtualDeclaration],
  source_imports: &[String],
) -> Result<(), TypeCheckerError> {
  let mut ctx = TypeContext {
    scopes: vec![Scope::new()],
    named_types: HashMap::new(),
    modules: HashMap::new(),
    namespace_types: HashMap::new(),
    source_imports: source_imports.iter().cloned().collect(),
    check_imports: !declarations.is_empty() || !source_imports.is_empty(),
    expected_returns: Vec::new(),
  };

  // Runtime globals with stable, useful surface types.
  ctx
    .scope_mut()
    .insert("undefined".to_string(), Type::Undefined);
  ctx.scope_mut().insert(
    "isNaN".to_string(),
    Type::Function(vec![Type::Number], Box::new(Type::Boolean)),
  );
  ctx.scope_mut().insert(
    "isFinite".to_string(),
    Type::Function(vec![Type::Number], Box::new(Type::Boolean)),
  );
  ctx.scope_mut().insert(
    "parseInt".to_string(),
    Type::Function(vec![Type::String], Box::new(Type::Number)),
  );
  ctx.scope_mut().insert(
    "parseFloat".to_string(),
    Type::Function(vec![Type::String], Box::new(Type::Number)),
  );
  ctx.scope_mut().insert(
    "console".to_string(),
    Type::Object(HashMap::from([(
      "log".to_string(),
      Type::Function(Vec::new(), Box::new(Type::Void)),
    )])),
  );
  ctx
    .scope_mut()
    .insert("process".to_string(), Type::Any);

  ctx.register_declarations_sources(declarations)?;

  for stmt in &program.body {
    ctx.register_declarations(stmt)?;
  }

  for stmt in &program.body {
    ctx.check_statement_oast(stmt)?;
  }
  Ok(())
}

struct TypeContext {
  scopes: Vec<Scope>,
  named_types: HashMap<String, TypeDefinition>,
  modules: HashMap<String, ModuleType>,
  namespace_types: HashMap<String, TypeDefinition>,
  source_imports: HashSet<String>,
  check_imports: bool,
  expected_returns: Vec<Type>,
}

struct ParsedDeclaration {
  specifier: String,
  session: crate::parser::ParserSession,
}

fn private_type_name(
  specifier: &str,
  name: &str,
) -> String {
  // The NUL prefix cannot be produced by an ECMAScript identifier, so a
  // private helper cannot collide with a user-visible type name.
  format!("\0virtual-module:{specifier}:{name}")
}

fn qualify_type_definition(
  specifier: &str,
  local_types: &HashSet<String>,
  definition: &TypeDefinition,
) -> TypeDefinition {
  let generic_names = definition
    .parameters
    .iter()
    .map(|parameter| parameter.name.clone())
    .collect();
  TypeDefinition {
    parameters: definition
      .parameters
      .iter()
      .map(|parameter| TypeParameter {
        name: parameter.name.clone(),
        constraint: parameter
          .constraint
          .as_ref()
          .map(|typ| qualify_type(specifier, local_types, &generic_names, typ)),
        default: parameter
          .default
          .as_ref()
          .map(|typ| qualify_type(specifier, local_types, &generic_names, typ)),
      })
      .collect(),
    body: qualify_type(specifier, local_types, &generic_names, &definition.body),
  }
}

fn qualify_type(
  specifier: &str,
  local_types: &HashSet<String>,
  generic_names: &HashSet<String>,
  typ: &Type,
) -> Type {
  match typ {
    Type::Array(element) => Type::Array(Box::new(qualify_type(
      specifier,
      local_types,
      generic_names,
      element,
    ))),
    Type::Tuple(elements) => Type::Tuple(
      elements
        .iter()
        .map(|element| qualify_type(specifier, local_types, generic_names, element))
        .collect(),
    ),
    Type::Rest(element) => Type::Rest(Box::new(qualify_type(
      specifier,
      local_types,
      generic_names,
      element,
    ))),
    Type::Function(parameters, result) => Type::Function(
      parameters
        .iter()
        .map(|parameter| qualify_type(specifier, local_types, generic_names, parameter))
        .collect(),
      Box::new(qualify_type(specifier, local_types, generic_names, result)),
    ),
    Type::Object(properties) => Type::Object(
      properties
        .iter()
        .map(|(name, typ)| {
          (
            name.clone(),
            qualify_type(specifier, local_types, generic_names, typ),
          )
        })
        .collect(),
    ),
    Type::TypeReference { name, arguments } => Type::TypeReference {
      name: if local_types.contains(name) && !generic_names.contains(name) {
        private_type_name(specifier, name)
      } else {
        name.clone()
      },
      arguments: arguments
        .iter()
        .map(|argument| qualify_type(specifier, local_types, generic_names, argument))
        .collect(),
    },
    Type::Union(types) => Type::Union(
      types
        .iter()
        .map(|typ| qualify_type(specifier, local_types, generic_names, typ))
        .collect(),
    ),
    Type::Intersection(types) => Type::Intersection(
      types
        .iter()
        .map(|typ| qualify_type(specifier, local_types, generic_names, typ))
        .collect(),
    ),
    Type::Conditional {
      check,
      extends,
      true_type,
      false_type,
      distributive_parameter,
    } => Type::Conditional {
      check: Box::new(qualify_type(specifier, local_types, generic_names, check)),
      extends: Box::new(qualify_type(specifier, local_types, generic_names, extends)),
      true_type: Box::new(qualify_type(
        specifier,
        local_types,
        generic_names,
        true_type,
      )),
      false_type: Box::new(qualify_type(
        specifier,
        local_types,
        generic_names,
        false_type,
      )),
      distributive_parameter: distributive_parameter.clone(),
    },
    Type::KeyOf(operand) => Type::KeyOf(Box::new(qualify_type(
      specifier,
      local_types,
      generic_names,
      operand,
    ))),
    Type::IndexedAccess { object, index } => Type::IndexedAccess {
      object: Box::new(qualify_type(specifier, local_types, generic_names, object)),
      index: Box::new(qualify_type(specifier, local_types, generic_names, index)),
    },
    Type::Mapped {
      parameter,
      constraint,
      value,
    } => {
      let mut mapped_generics = generic_names.clone();
      mapped_generics.insert(parameter.clone());
      Type::Mapped {
        parameter: parameter.clone(),
        constraint: Box::new(qualify_type(
          specifier,
          local_types,
          generic_names,
          constraint,
        )),
        value: Box::new(qualify_type(
          specifier,
          local_types,
          &mapped_generics,
          value,
        )),
      }
    }
    Type::TemplateLiteral {
      quasis,
      substitutions,
    } => Type::TemplateLiteral {
      quasis: quasis.clone(),
      substitutions: substitutions
        .iter()
        .map(|typ| qualify_type(specifier, local_types, generic_names, typ))
        .collect(),
    },
    other => other.clone(),
  }
}

fn module_declaration_names(
  declaration: &oast::Declaration<'_>,
  values: &mut HashSet<String>,
  types: &mut HashSet<String>,
) {
  match declaration {
    oast::Declaration::TSTypeAliasDeclaration(alias) => {
      types.insert(alias.id.name.to_string());
    }
    oast::Declaration::TSInterfaceDeclaration(interface) => {
      types.insert(interface.id.name.to_string());
    }
    oast::Declaration::VariableDeclaration(variable) => {
      for declarator in &variable.declarations {
        if let oast::BindingPattern::BindingIdentifier(identifier) = &declarator.id {
          values.insert(identifier.name.to_string());
        }
      }
    }
    oast::Declaration::FunctionDeclaration(function) => {
      if let Some(identifier) = &function.id {
        values.insert(identifier.name.to_string());
      }
    }
    _ => {}
  }
}

impl TypeContext {
  fn register_declarations_sources(
    &mut self,
    declarations: &[VirtualDeclaration],
  ) -> Result<(), TypeCheckerError> {
    let source_type =
      crate::parser::Parser::source_type_for_path(std::path::Path::new("virtual.d.ts"), false);
    let mut parsed = Vec::with_capacity(declarations.len());
    for declaration in declarations {
      let session = crate::parser::Parser::parse_source_with_type(&declaration.source, source_type)
        .map_err(|error| {
          TypeCheckerError::from(format!(
            "Failed to parse declaration for '{}': {}",
            declaration.specifier, error
          ))
        })?;
      parsed.push(ParsedDeclaration {
        specifier: declaration.specifier.clone(),
        session,
      });
    }
    parsed.sort_by(|left, right| left.specifier.cmp(&right.specifier));
    if parsed
      .windows(2)
      .any(|pair| pair[0].specifier == pair[1].specifier)
    {
      return Err(TypeCheckerError::from("Duplicate declaration module"));
    }

    // Collect every top-level declaration in a module-local table first. Type
    // annotations are allowed to refer to private helpers, but the public
    // ModuleType is filtered back to the module's actual exports below.
    for declaration in &parsed {
      let mut local = ModuleType::default();
      let mut exported_values = HashSet::new();
      let mut exported_types = HashSet::new();
      let mut export_aliases = Vec::new();
      for statement in &declaration.session.program().body {
        match statement {
          oast::Statement::ExportNamedDeclaration(export) => {
            if let Some(declaration) = &export.declaration {
              self.register_module_declaration(declaration, &mut local)?;
              module_declaration_names(declaration, &mut exported_values, &mut exported_types);
            } else if export.source.is_none() {
              for specifier in &export.specifiers {
                export_aliases.push((
                  module_export_name(&specifier.local)?,
                  module_export_name(&specifier.exported)?,
                ));
              }
            }
          }
          oast::Statement::TSTypeAliasDeclaration(_)
          | oast::Statement::TSInterfaceDeclaration(_)
          | oast::Statement::VariableDeclaration(_)
          | oast::Statement::FunctionDeclaration(_) => {
            self.register_module_statement_declaration(statement, &mut local)?;
          }
          _ => {}
        }
      }

      let local_type_names: HashSet<String> = local.types.keys().cloned().collect();
      let mut qualified_types = HashMap::new();
      for (name, definition) in local.types {
        let definition =
          qualify_type_definition(&declaration.specifier, &local_type_names, &definition);
        self.named_types.insert(
          private_type_name(&declaration.specifier, &name),
          definition.clone(),
        );
        qualified_types.insert(name, definition);
      }
      let qualified_values = local
        .values
        .into_iter()
        .map(|(name, typ)| {
          (
            name,
            qualify_type(
              &declaration.specifier,
              &local_type_names,
              &HashSet::new(),
              &typ,
            ),
          )
        })
        .collect::<HashMap<_, _>>();
      let mut public_values = qualified_values
        .iter()
        .filter(|(name, _)| exported_values.contains(*name))
        .map(|(name, typ)| (name.clone(), typ.clone()))
        .collect::<HashMap<_, _>>();
      let mut public_types = qualified_types
        .iter()
        .filter(|(name, _)| exported_types.contains(*name))
        .map(|(name, definition)| (name.clone(), definition.clone()))
        .collect::<HashMap<_, _>>();
      for (local_name, exported_name) in export_aliases {
        if let Some(definition) = qualified_types.get(&local_name) {
          public_types.insert(exported_name, definition.clone());
        } else if let Some(typ) = qualified_values.get(&local_name) {
          public_values.insert(exported_name, typ.clone());
        }
      }
      let module = ModuleType {
        values: public_values,
        types: public_types,
        namespaces: HashMap::new(),
      };
      self
        .modules
        .insert(declaration.specifier.clone(), module);
    }

    // Public type names remain available to source annotations and namespace
    // imports. Private helpers are reachable only through the internal names
    // embedded in the exported definitions above.
    let mut definitions = Vec::new();
    for (specifier, module) in &self.modules {
      definitions.extend(
        module
          .types
          .iter()
          .map(|(name, definition)| (name.clone(), specifier.clone(), definition.clone())),
      );
    }
    definitions.sort_by(|left, right| {
      left
        .0
        .cmp(&right.0)
        .then_with(|| left.1.cmp(&right.1))
    });
    for (name, _, definition) in definitions {
      self.named_types.entry(name).or_insert(definition);
    }

    // Resolve imports and re-exports to a fixed point. The bounded number of
    // passes is sufficient for the finite declaration graph and deterministic.
    for _ in 0..=parsed.len() {
      for declaration in &parsed {
        let mut module = self
          .modules
          .get(&declaration.specifier)
          .cloned()
          .expect("direct declaration module was inserted");
        for statement in &declaration.session.program().body {
          self.register_module_links(statement, &mut module)?;
        }
        self
          .modules
          .insert(declaration.specifier.clone(), module);
      }
    }

    // Validate re-exported members after all dependency links have converged.
    for declaration in &parsed {
      let mut module = self
        .modules
        .get(&declaration.specifier)
        .cloned()
        .expect("linked declaration module was inserted");
      for statement in &declaration.session.program().body {
        self.register_module_links_strict(statement, &mut module)?;
      }
      self
        .modules
        .insert(declaration.specifier.clone(), module);
    }
    Ok(())
  }

  fn register_module_links(
    &mut self,
    statement: &oast::Statement<'_>,
    module: &mut ModuleType,
  ) -> Result<(), TypeCheckerError> {
    match statement {
      oast::Statement::ImportDeclaration(import) => {
        self.register_module_import(import, false)?;
      }
      oast::Statement::ExportNamedDeclaration(export) => {
        if let Some(source) = &export.source {
          self.register_reexport(source.value.as_str(), &export.specifiers, module, false)?;
        }
      }
      oast::Statement::ExportAllDeclaration(export) => {
        self.register_export_all(export, module)?;
      }
      _ => {}
    }
    Ok(())
  }

  fn register_module_links_strict(
    &mut self,
    statement: &oast::Statement<'_>,
    module: &mut ModuleType,
  ) -> Result<(), TypeCheckerError> {
    match statement {
      oast::Statement::ImportDeclaration(import) => {
        self.register_module_import(import, true)?;
      }
      oast::Statement::ExportNamedDeclaration(export) => {
        if let Some(source) = &export.source {
          self.register_reexport(source.value.as_str(), &export.specifiers, module, true)?;
        }
      }
      oast::Statement::ExportAllDeclaration(export) => {
        self.register_export_all(export, module)?;
      }
      _ => {}
    }
    Ok(())
  }

  fn register_module_import(
    &mut self,
    import: &oast::ImportDeclaration<'_>,
    strict: bool,
  ) -> Result<(), TypeCheckerError> {
    let source = import.source.value.as_str();
    let module = self.module(source)?.clone();
    let Some(specifiers) = &import.specifiers else {
      return Ok(());
    };
    for specifier in specifiers {
      match specifier {
        oast::ImportDeclarationSpecifier::ImportNamespaceSpecifier(namespace) => {
          register_namespace_types(
            namespace.local.name.as_str(),
            &module,
            &mut self.namespace_types,
          );
        }
        oast::ImportDeclarationSpecifier::ImportDefaultSpecifier(_) => {}
        oast::ImportDeclarationSpecifier::ImportSpecifier(named) => {
          let imported = module_export_name(&named.imported)?;
          if let Some(definition) = module.types.get(&imported) {
            self
              .named_types
              .insert(named.local.name.to_string(), definition.clone());
          } else if !module.values.contains_key(&imported) && strict {
            return Err(TypeCheckerError::from(format!(
              "Module '{source}' has no export '{imported}'"
            )));
          }
        }
      }
    }
    Ok(())
  }

  fn register_reexport(
    &mut self,
    source: &str,
    specifiers: &[oast::ExportSpecifier<'_>],
    module: &mut ModuleType,
    strict: bool,
  ) -> Result<(), TypeCheckerError> {
    let imported = self.module(source)?.clone();
    for specifier in specifiers {
      let local = module_export_name(&specifier.local)?;
      let exported = module_export_name(&specifier.exported)?;
      if let Some(typ) = imported.values.get(&local) {
        module.values.insert(exported, typ.clone());
      } else if let Some(definition) = imported.types.get(&local) {
        module.types.insert(exported, definition.clone());
      } else if strict {
        return Err(TypeCheckerError::from(format!(
          "Module '{source}' has no export '{local}'"
        )));
      }
    }
    Ok(())
  }

  fn register_export_all(
    &mut self,
    export: &oast::ExportAllDeclaration<'_>,
    module: &mut ModuleType,
  ) -> Result<(), TypeCheckerError> {
    let imported = self.module(export.source.value.as_str())?.clone();
    if let Some(exported) = &export.exported {
      module
        .namespaces
        .insert(module_export_name(exported)?, imported);
    } else if export.export_kind == oast::ImportOrExportKind::Type {
      module.types.extend(imported.types);
      module.namespaces.extend(imported.namespaces);
    } else {
      module.values.extend(imported.values);
      module.types.extend(imported.types);
      module.namespaces.extend(imported.namespaces);
    }
    Ok(())
  }

  fn module(
    &self,
    source: &str,
  ) -> Result<&ModuleType, TypeCheckerError> {
    self
      .modules
      .get(source)
      .ok_or_else(|| TypeCheckerError::from(format!("Unknown declaration module '{source}'")))
  }

  fn register_module_statement_declaration(
    &mut self,
    statement: &oast::Statement<'_>,
    module: &mut ModuleType,
  ) -> Result<(), TypeCheckerError> {
    match statement {
      oast::Statement::TSTypeAliasDeclaration(alias) => {
        module.types.insert(
          alias.id.name.to_string(),
          type_definition(alias.type_parameters.as_deref(), &alias.type_annotation)?,
        );
      }
      oast::Statement::TSInterfaceDeclaration(interface) => {
        module.types.insert(
          interface.id.name.to_string(),
          TypeDefinition {
            parameters: convert_type_parameters(interface.type_parameters.as_deref())?,
            body: self.interface_type(interface)?,
          },
        );
      }
      oast::Statement::VariableDeclaration(variable) => {
        for declarator in &variable.declarations {
          let oast::BindingPattern::BindingIdentifier(identifier) = &declarator.id else {
            return Err(TypeCheckerError::from(
              "unsupported declaration binding pattern",
            ));
          };
          let typ = declarator
            .type_annotation
            .as_deref()
            .map(convert_type_ann)
            .transpose()?
            .unwrap_or(Type::Unknown);
          module
            .values
            .insert(identifier.name.to_string(), typ);
        }
      }
      oast::Statement::FunctionDeclaration(function) => {
        if let Some(identifier) = &function.id {
          let typ = self.function_type(&function.params, function.return_type.as_deref())?;
          merge_callable(&mut module.values, identifier.name.as_str(), typ);
        }
      }
      _ => {}
    }
    Ok(())
  }

  fn register_module_declaration(
    &mut self,
    declaration: &oast::Declaration<'_>,
    module: &mut ModuleType,
  ) -> Result<(), TypeCheckerError> {
    match declaration {
      oast::Declaration::TSTypeAliasDeclaration(alias) => {
        module.types.insert(
          alias.id.name.to_string(),
          type_definition(alias.type_parameters.as_deref(), &alias.type_annotation)?,
        );
      }
      oast::Declaration::TSInterfaceDeclaration(interface) => {
        module.types.insert(
          interface.id.name.to_string(),
          TypeDefinition {
            parameters: convert_type_parameters(interface.type_parameters.as_deref())?,
            body: self.interface_type(interface)?,
          },
        );
      }
      oast::Declaration::VariableDeclaration(variable) => {
        for declarator in &variable.declarations {
          let oast::BindingPattern::BindingIdentifier(identifier) = &declarator.id else {
            return Err(TypeCheckerError::from(
              "unsupported declaration binding pattern",
            ));
          };
          let typ = declarator
            .type_annotation
            .as_deref()
            .map(convert_type_ann)
            .transpose()?
            .unwrap_or(Type::Unknown);
          module
            .values
            .insert(identifier.name.to_string(), typ);
        }
      }
      oast::Declaration::FunctionDeclaration(function) => {
        if let Some(identifier) = &function.id {
          let typ = self.function_type(&function.params, function.return_type.as_deref())?;
          merge_callable(&mut module.values, identifier.name.as_str(), typ);
        }
      }
      _ => {}
    }
    Ok(())
  }

  fn scope_mut(&mut self) -> &mut Scope {
    self
      .scopes
      .last_mut()
      .expect("scope stack is empty: attempted to borrow mutable scope but no scopes are present")
  }

  fn lookup(
    &self,
    name: &str,
  ) -> Option<Type> {
    for s in self.scopes.iter().rev() {
      if let Some(t) = s.get(name) {
        return Some(t.clone());
      }
    }
    None
  }

  fn register_declarations(
    &mut self,
    stmt: &oast::Statement<'_>,
  ) -> Result<(), TypeCheckerError> {
    match stmt {
      oast::Statement::TSTypeAliasDeclaration(alias) => {
        self.named_types.insert(
          alias.id.name.to_string(),
          type_definition(alias.type_parameters.as_deref(), &alias.type_annotation)?,
        );
      }
      oast::Statement::TSInterfaceDeclaration(interface) => {
        let typ = self.interface_type(interface)?;
        self.named_types.insert(
          interface.id.name.to_string(),
          TypeDefinition {
            parameters: convert_type_parameters(interface.type_parameters.as_deref())?,
            body: typ,
          },
        );
      }
      oast::Statement::FunctionDeclaration(function) => {
        if let Some(id) = &function.id {
          let typ = self.function_type(&function.params, function.return_type.as_deref())?;
          merge_callable_scope(self.scope_mut(), id.name.as_str(), typ);
        }
      }
      oast::Statement::VariableDeclaration(variable) => {
        for declarator in &variable.declarations {
          let oast::BindingPattern::BindingIdentifier(identifier) = &declarator.id else {
            return Err(TypeCheckerError::from(
              "unsupported variable binding pattern",
            ));
          };
          let typ = declarator
            .type_annotation
            .as_deref()
            .map(convert_type_ann)
            .transpose()?
            .unwrap_or(Type::Unknown);
          self
            .scope_mut()
            .insert(identifier.name.to_string(), typ);
        }
      }
      oast::Statement::ImportDeclaration(import) if self.check_imports => {
        self.register_import(import)?;
      }
      oast::Statement::ExportNamedDeclaration(export) => {
        if let Some(declaration) = &export.declaration {
          self.register_exported_declaration(declaration)?;
        }
      }
      _ => {}
    }
    Ok(())
  }

  fn register_source_import(
    &mut self,
    import: &oast::ImportDeclaration<'_>,
  ) {
    let Some(specifiers) = &import.specifiers else {
      return;
    };
    for specifier in specifiers {
      match specifier {
        oast::ImportDeclarationSpecifier::ImportNamespaceSpecifier(namespace) => {
          self
            .scope_mut()
            .insert(namespace.local.name.to_string(), Type::Unknown);
        }
        oast::ImportDeclarationSpecifier::ImportDefaultSpecifier(default) => {
          self
            .scope_mut()
            .insert(default.local.name.to_string(), Type::Unknown);
        }
        oast::ImportDeclarationSpecifier::ImportSpecifier(named) => {
          self
            .scope_mut()
            .insert(named.local.name.to_string(), Type::Unknown);
          self.named_types.insert(
            named.local.name.to_string(),
            TypeDefinition {
              parameters: Vec::new(),
              body: Type::Unknown,
            },
          );
        }
      }
    }
  }

  fn register_import(
    &mut self,
    import: &oast::ImportDeclaration<'_>,
  ) -> Result<(), TypeCheckerError> {
    let source = import.source.value.as_str();
    let Some(module) = self.modules.get(source).cloned() else {
      if self.source_imports.contains(source) {
        self.register_source_import(import);
        return Ok(());
      }
      return Err(TypeCheckerError::from(format!(
        "Unknown declaration module '{source}'"
      )));
    };
    let Some(specifiers) = &import.specifiers else {
      return Ok(());
    };
    for specifier in specifiers {
      match specifier {
        oast::ImportDeclarationSpecifier::ImportNamespaceSpecifier(namespace) => {
          self.scope_mut().insert(
            namespace.local.name.to_string(),
            Type::Object(module_namespace_values(&module)),
          );
          register_namespace_types(
            namespace.local.name.as_str(),
            &module,
            &mut self.namespace_types,
          );
        }
        oast::ImportDeclarationSpecifier::ImportDefaultSpecifier(default) => {
          let typ = module.values.get("default").ok_or_else(|| {
            TypeCheckerError::from(format!("Module '{source}' has no default export"))
          })?;
          self
            .scope_mut()
            .insert(default.local.name.to_string(), typ.clone());
        }
        oast::ImportDeclarationSpecifier::ImportSpecifier(named) => {
          let imported = module_export_name(&named.imported)?;
          if let Some(typ) = module.values.get(&imported) {
            self
              .scope_mut()
              .insert(named.local.name.to_string(), typ.clone());
          } else if let Some(definition) = module.types.get(&imported) {
            self
              .named_types
              .insert(named.local.name.to_string(), definition.clone());
          } else {
            return Err(TypeCheckerError::from(format!(
              "Module '{source}' has no export '{imported}'"
            )));
          }
        }
      }
    }
    Ok(())
  }

  fn register_exported_declaration(
    &mut self,
    declaration: &oast::Declaration<'_>,
  ) -> Result<(), TypeCheckerError> {
    match declaration {
      oast::Declaration::TSTypeAliasDeclaration(alias) => {
        self.named_types.insert(
          alias.id.name.to_string(),
          type_definition(alias.type_parameters.as_deref(), &alias.type_annotation)?,
        );
      }
      oast::Declaration::TSInterfaceDeclaration(interface) => {
        let typ = self.interface_type(interface)?;
        self.named_types.insert(
          interface.id.name.to_string(),
          TypeDefinition {
            parameters: convert_type_parameters(interface.type_parameters.as_deref())?,
            body: typ,
          },
        );
      }
      oast::Declaration::FunctionDeclaration(function) => {
        if let Some(id) = &function.id {
          let typ = self.function_type(&function.params, function.return_type.as_deref())?;
          merge_callable_scope(self.scope_mut(), id.name.as_str(), typ);
        }
      }
      oast::Declaration::VariableDeclaration(variable) => {
        for declarator in &variable.declarations {
          let oast::BindingPattern::BindingIdentifier(identifier) = &declarator.id else {
            return Err(TypeCheckerError::from(
              "unsupported variable binding pattern",
            ));
          };
          let typ = declarator
            .type_annotation
            .as_deref()
            .map(convert_type_ann)
            .transpose()?
            .unwrap_or(Type::Unknown);
          self
            .scope_mut()
            .insert(identifier.name.to_string(), typ);
        }
      }
      _ => {}
    }
    Ok(())
  }

  fn interface_type(
    &self,
    interface: &oast::TSInterfaceDeclaration<'_>,
  ) -> Result<Type, TypeCheckerError> {
    let mut properties = HashMap::new();
    let mut call_signatures = Vec::new();
    for signature in &interface.body.body {
      match signature {
        oast::TSSignature::TSPropertySignature(property) => {
          if let Some(name) = property_name(&property.key) {
            let typ = property
              .type_annotation
              .as_deref()
              .map(convert_type_ann)
              .transpose()?
              .unwrap_or(Type::Unknown);
            properties.insert(
              name,
              if property.optional {
                Type::Union(vec![typ, Type::Undefined])
              } else {
                typ
              },
            );
          }
        }
        oast::TSSignature::TSMethodSignature(method) => {
          if let Some(name) = property_name(&method.key) {
            properties.insert(
              name,
              self.function_type(&method.params, method.return_type.as_deref())?,
            );
          }
        }
        oast::TSSignature::TSCallSignatureDeclaration(call) => {
          call_signatures.push(function_type_from_call_signature(call)?);
        }
        _ => {}
      }
    }
    if !call_signatures.is_empty() {
      if properties.is_empty() {
        return Ok(normalize_union(call_signatures));
      }
      properties.insert("[[call]]".to_string(), normalize_union(call_signatures));
    }
    Ok(Type::Object(properties))
  }

  fn function_type(
    &self,
    params: &oast::FormalParameters<'_>,
    return_type: Option<&oast::TSTypeAnnotation<'_>>,
  ) -> Result<Type, TypeCheckerError> {
    let mut parameter_types = Vec::new();
    for parameter in &params.items {
      parameter_types.push(
        parameter
          .type_annotation
          .as_deref()
          .map(convert_type_ann)
          .transpose()?
          .unwrap_or(Type::Any),
      );
    }
    if let Some(rest) = &params.rest {
      parameter_types.push(
        rest
          .type_annotation
          .as_deref()
          .map(convert_type_ann)
          .transpose()?
          .unwrap_or(Type::Any),
      );
    }
    let return_type = return_type
      .map(convert_type_ann)
      .transpose()?
      .unwrap_or(Type::Any);
    Ok(Type::Function(parameter_types, Box::new(return_type)))
  }

  fn resolve_type(
    &self,
    typ: &Type,
  ) -> Type {
    self.resolve_type_with_environment(typ, &TypeEnvironment::new(), 0)
  }

  fn resolve_type_with_environment(
    &self,
    typ: &Type,
    environment: &TypeEnvironment,
    depth: usize,
  ) -> Type {
    if depth >= TYPE_EVALUATION_LIMIT {
      return Type::Unknown;
    }
    match typ {
      Type::TypeReference { name, arguments } => {
        if let Some(bound) = environment.get(name) {
          return self.resolve_type_with_environment(bound, environment, depth + 1);
        }
        if name == "Exclude" && arguments.len() >= 2 {
          let source = self.resolve_type_with_environment(&arguments[0], environment, depth + 1);
          let excluded = self.resolve_type_with_environment(&arguments[1], environment, depth + 1);
          return normalize_union(
            union_members(source)
              .into_iter()
              .filter(|member| !assignable(&excluded, member))
              .collect(),
          );
        }
        if name == "ReadonlyArray"
          && let Some(element) = arguments.first()
        {
          return Type::Array(Box::new(self.resolve_type_with_environment(
            element,
            environment,
            depth + 1,
          )));
        }
        if name == "Record" && arguments.len() >= 2 {
          let keys = self.resolve_type_with_environment(&arguments[0], environment, depth + 1);
          let value = self.resolve_type_with_environment(&arguments[1], environment, depth + 1);
          return Type::Object(
            union_members(keys)
              .into_iter()
              .filter_map(|key| property_key_from_type(&key).map(|key| (key, value.clone())))
              .collect(),
          );
        }
        let definition = self
          .namespace_types
          .get(name)
          .cloned()
          .or_else(|| self.named_types.get(name).cloned());
        let Some(definition) = definition else {
          return Type::Unknown;
        };
        let mut definition_environment = environment.clone();
        for (index, parameter) in definition.parameters.iter().enumerate() {
          let argument = arguments
            .get(index)
            .cloned()
            .or_else(|| parameter.default.clone());
          let argument = argument
            .map(|typ| self.resolve_type_with_environment(&typ, environment, depth + 1))
            .unwrap_or(Type::Unknown);
          if let Some(constraint) = &parameter.constraint {
            let constraint =
              self.resolve_type_with_environment(constraint, &definition_environment, depth + 1);
            if !assignable(&constraint, &argument) {
              return Type::Never;
            }
          }
          definition_environment.insert(parameter.name.clone(), argument);
        }
        self.resolve_type_with_environment(&definition.body, &definition_environment, depth + 1)
      }
      Type::Array(element) => Type::Array(Box::new(self.resolve_type_with_environment(
        element,
        environment,
        depth + 1,
      ))),
      Type::Tuple(elements) => Type::Tuple(
        elements
          .iter()
          .map(|element| self.resolve_type_with_environment(element, environment, depth + 1))
          .collect(),
      ),
      Type::Rest(element) => Type::Rest(Box::new(self.resolve_type_with_environment(
        element,
        environment,
        depth + 1,
      ))),
      Type::Infer(_) => typ.clone(),
      Type::Object(properties) => Type::Object(
        properties
          .iter()
          .map(|(name, typ)| {
            (
              name.clone(),
              self.resolve_type_with_environment(typ, environment, depth + 1),
            )
          })
          .collect(),
      ),
      Type::Function(parameters, return_type) => Type::Function(
        parameters
          .iter()
          .map(|typ| self.resolve_type_with_environment(typ, environment, depth + 1))
          .collect(),
        Box::new(self.resolve_type_with_environment(return_type, environment, depth + 1)),
      ),
      Type::Union(types) => normalize_union(
        types
          .iter()
          .map(|typ| self.resolve_type_with_environment(typ, environment, depth + 1))
          .collect(),
      ),
      Type::Intersection(types) => self.resolve_intersection(types, environment, depth + 1),
      Type::Conditional {
        check,
        extends,
        true_type,
        false_type,
        distributive_parameter,
      } => {
        if let Some(parameter) = distributive_parameter
          && let Some(Type::Union(members)) = environment.get(parameter)
        {
          let distributed = members
            .iter()
            .map(|member| {
              let mut member_environment = environment.clone();
              member_environment.insert(parameter.clone(), member.clone());
              self.resolve_conditional(
                check,
                extends,
                true_type,
                false_type,
                &member_environment,
                depth + 1,
              )
            })
            .collect();
          return normalize_union(distributed);
        }
        self.resolve_conditional(
          check,
          extends,
          true_type,
          false_type,
          environment,
          depth + 1,
        )
      }
      Type::KeyOf(object) => {
        let object = self.resolve_type_with_environment(object, environment, depth + 1);
        match object {
          Type::Object(properties) => normalize_union(
            properties
              .keys()
              .map(|key| Type::Literal(LiteralType::String(key.clone())))
              .collect(),
          ),
          Type::Array(_) | Type::Tuple(_) => Type::Number,
          _ => Type::Unknown,
        }
      }
      Type::IndexedAccess { object, index } => {
        let object = self.resolve_type_with_environment(object, environment, depth + 1);
        let index = self.resolve_type_with_environment(index, environment, depth + 1);
        resolve_indexed_access(&object, &index)
      }
      Type::Mapped {
        parameter,
        constraint,
        value,
      } => {
        let constraint = self.resolve_type_with_environment(constraint, environment, depth + 1);
        let mut properties = HashMap::new();
        for key_type in union_members(constraint) {
          if let Some(key) = property_key_from_type(&key_type) {
            let mut mapped_environment = environment.clone();
            mapped_environment.insert(parameter.clone(), key_type);
            let value = self.resolve_type_with_environment(value, &mapped_environment, depth + 1);
            properties.insert(key, value);
          }
        }
        Type::Object(properties)
      }
      Type::TemplateLiteral {
        quasis,
        substitutions,
      } => {
        let substitutions: Vec<Type> = substitutions
          .iter()
          .map(|typ| self.resolve_type_with_environment(typ, environment, depth + 1))
          .collect();
        evaluate_template_literal(quasis, &substitutions)
      }
      _ => typ.clone(),
    }
  }

  fn resolve_conditional(
    &self,
    check: &Type,
    extends: &Type,
    true_type: &Type,
    false_type: &Type,
    environment: &TypeEnvironment,
    depth: usize,
  ) -> Type {
    let check = self.resolve_type_with_environment(check, environment, depth + 1);
    let extends = self.resolve_type_with_environment(extends, environment, depth + 1);
    let mut inferred_environment = environment.clone();
    let (branch, branch_environment) =
      if self.match_type_pattern(&extends, &check, &mut inferred_environment, depth + 1) {
        (true_type, &inferred_environment)
      } else {
        (false_type, environment)
      };
    self.resolve_type_with_environment(branch, branch_environment, depth + 1)
  }

  fn match_type_pattern(
    &self,
    pattern: &Type,
    actual: &Type,
    environment: &mut TypeEnvironment,
    depth: usize,
  ) -> bool {
    if depth >= TYPE_EVALUATION_LIMIT {
      return true;
    }
    match pattern {
      Type::Infer(name) => {
        environment.insert(name.clone(), actual.clone());
        true
      }
      Type::Tuple(pattern_elements) => {
        let Type::Tuple(actual_elements) = actual else {
          return false;
        };
        let rest_position = pattern_elements
          .iter()
          .position(|element| matches!(element, Type::Rest(_)));
        if rest_position.is_none() && pattern_elements.len() != actual_elements.len() {
          return false;
        }
        if let Some(position) = rest_position {
          if actual_elements.len() < position {
            return false;
          }
          for (pattern, actual) in pattern_elements[..position]
            .iter()
            .zip(actual_elements.iter())
          {
            if !self.match_type_pattern(pattern, actual, environment, depth + 1) {
              return false;
            }
          }
          let Type::Rest(rest) = &pattern_elements[position] else {
            return false;
          };
          if let Type::Infer(name) = rest.as_ref() {
            environment.insert(
              name.clone(),
              Type::Tuple(actual_elements[position..].to_vec()),
            );
            return true;
          }
          let rest_element = match rest.as_ref() {
            Type::Array(element) => element.as_ref(),
            other => other,
          };
          actual_elements[position..]
            .iter()
            .all(|actual| self.match_type_pattern(rest_element, actual, environment, depth + 1))
        } else {
          pattern_elements
            .iter()
            .zip(actual_elements.iter())
            .all(|(pattern, actual)| {
              self.match_type_pattern(pattern, actual, environment, depth + 1)
            })
        }
      }
      Type::Array(pattern_element) => match actual {
        Type::Array(actual_element) => {
          self.match_type_pattern(pattern_element, actual_element, environment, depth + 1)
        }
        Type::Tuple(actual_elements) => actual_elements
          .iter()
          .all(|actual| self.match_type_pattern(pattern_element, actual, environment, depth + 1)),
        _ => false,
      },
      _ => assignable(pattern, actual),
    }
  }

  fn resolve_intersection(
    &self,
    types: &[Type],
    environment: &TypeEnvironment,
    depth: usize,
  ) -> Type {
    let resolved: Vec<Type> = types
      .iter()
      .map(|typ| self.resolve_type_with_environment(typ, environment, depth + 1))
      .collect();
    if resolved
      .iter()
      .all(|typ| matches!(typ, Type::Object(_)))
    {
      let mut properties = HashMap::new();
      for typ in resolved {
        if let Type::Object(object_properties) = typ {
          properties.extend(object_properties);
        }
      }
      Type::Object(properties)
    } else {
      Type::Intersection(resolved)
    }
  }

  fn is_assignable(
    &self,
    expected: &Type,
    actual: &Type,
  ) -> bool {
    assignable(&self.resolve_type(expected), &self.resolve_type(actual))
  }

  fn check_variable_declaration(
    &mut self,
    declaration: &oast::VariableDeclaration<'_>,
  ) -> Result<(), TypeCheckerError> {
    for declarator in &declaration.declarations {
      let name = match &declarator.id {
        oast::BindingPattern::BindingIdentifier(identifier) => identifier.name.to_string(),
        _ => {
          return Err(TypeCheckerError::from(
            "unsupported variable binding pattern",
          ));
        }
      };
      let declared_type = declarator
        .type_annotation
        .as_deref()
        .map(convert_type_ann)
        .transpose()?;
      let mut initializer_type = declarator
        .init
        .as_ref()
        .map(|initializer| self.type_of_expr_oast(initializer))
        .transpose()?;
      if declarator.type_annotation.is_none()
        && !matches!(declaration.kind, oast::VariableDeclarationKind::Const)
      {
        initializer_type = initializer_type.map(widen_literal);
      }
      let variable_type = declared_type
        .clone()
        .or_else(|| initializer_type.clone())
        .unwrap_or(Type::Any);

      if let (Some(expected), Some(actual)) = (&declared_type, &initializer_type)
        && !self.is_assignable(expected, actual)
      {
        return Err(TypeCheckerError::from(format!(
          "Type '{}' is not assignable to '{}' for variable '{}'",
          type_to_string(actual),
          type_to_string(expected),
          name
        )));
      }
      self.scope_mut().insert(name, variable_type);
    }
    Ok(())
  }

  fn check_function(
    &mut self,
    function: &oast::Function<'_>,
  ) -> Result<(), TypeCheckerError> {
    let return_type = function
      .return_type
      .as_deref()
      .map(convert_type_ann)
      .transpose()?
      .unwrap_or(Type::Any);
    let Some(body) = &function.body else {
      return Ok(());
    };

    if strict_mode() {
      for parameter in &function.params.items {
        if parameter.type_annotation.is_none()
          && let oast::BindingPattern::BindingIdentifier(identifier) = &parameter.pattern
        {
          return Err(TypeCheckerError::from(format!(
            "Parameter '{}' implicitly has type 'any'",
            identifier.name
          )));
        }
      }
    }

    self.scopes.push(Scope::new());
    for parameter in &function.params.items {
      if let oast::BindingPattern::BindingIdentifier(identifier) = &parameter.pattern {
        let typ = parameter
          .type_annotation
          .as_deref()
          .map(convert_type_ann)
          .transpose()?
          .unwrap_or(Type::Any);
        self
          .scope_mut()
          .insert(identifier.name.to_string(), typ);
      }
    }
    if let Some(rest) = &function.params.rest
      && let oast::BindingPattern::BindingIdentifier(identifier) = &rest.rest.argument
    {
      let typ = rest
        .type_annotation
        .as_deref()
        .map(convert_type_ann)
        .transpose()?
        .unwrap_or(Type::Any);
      self
        .scope_mut()
        .insert(identifier.name.to_string(), typ);
    }
    self.expected_returns.push(return_type);
    let result = body
      .statements
      .iter()
      .try_for_each(|statement| self.check_statement_oast(statement));
    self.expected_returns.pop();
    self.scopes.pop();
    result
  }

  fn check_exported_declaration(
    &mut self,
    declaration: &oast::Declaration<'_>,
  ) -> Result<(), TypeCheckerError> {
    match declaration {
      oast::Declaration::VariableDeclaration(variable) => self.check_variable_declaration(variable),
      oast::Declaration::FunctionDeclaration(function) => self.check_function(function),
      _ => Ok(()),
    }
  }

  /// Checks a single OAST statement and updates the type context accordingly.
  ///
  /// # Errors
  ///
  /// Returns a `TypeCheckerError` if the statement cannot be typechecked.
  #[allow(clippy::too_many_lines)]
  fn check_statement_oast(
    &mut self,
    stmt: &oast::Statement,
  ) -> Result<(), TypeCheckerError> {
    use oast::Statement as OStmt;
    match stmt {
      OStmt::VariableDeclaration(variable) => self.check_variable_declaration(variable)?,
      OStmt::FunctionDeclaration(function) => self.check_function(function)?,
      OStmt::ExportNamedDeclaration(export) => {
        if let Some(declaration) = &export.declaration {
          self.check_exported_declaration(declaration)?;
        }
      }
      OStmt::ExpressionStatement(e) => {
        drop(self.type_of_expr_oast(&e.expression)?);
      }
      OStmt::BlockStatement(b) => {
        self.scopes.push(Scope::new());
        let result = b
          .body
          .iter()
          .try_for_each(|statement| self.check_statement_oast(statement));
        self.scopes.pop();
        result?;
      }
      OStmt::IfStatement(i) => {
        drop(self.type_of_expr_oast(&i.test)?);
        self.check_statement_oast(&i.consequent)?;
        if let Some(alt) = &i.alternate {
          self.check_statement_oast(alt)?;
        }
      }
      OStmt::WhileStatement(w) => {
        drop(self.type_of_expr_oast(&w.test)?);
        self.check_statement_oast(&w.body)?;
      }
      OStmt::ReturnStatement(r) => {
        let actual = r
          .argument
          .as_ref()
          .map(|argument| self.type_of_expr_oast(argument))
          .transpose()?
          .unwrap_or(Type::Void);
        if let Some(expected) = self.expected_returns.last()
          && !self.is_assignable(expected, &actual)
        {
          return Err(TypeCheckerError::from(format!(
            "Type '{}' is not assignable to function return type '{}'",
            type_to_string(&actual),
            type_to_string(expected)
          )));
        }
      }
      _ => {}
    }
    Ok(())
  }

  fn call_type(
    &mut self,
    callee: &Type,
    call: &oast::CallExpression<'_>,
  ) -> Result<Type, TypeCheckerError> {
    let candidates = match callee {
      Type::Union(types) => types.clone(),
      other => vec![other.clone()],
    };
    let mut arguments = Vec::new();
    for argument in &call.arguments {
      let expression = argument
        .as_expression()
        .ok_or_else(|| TypeCheckerError::from("Unsupported call argument"))?;
      arguments.push(self.type_of_expr_oast(expression)?);
    }
    let explicit_types = call
      .type_arguments
      .as_ref()
      .map(|arguments| {
        arguments
          .params
          .iter()
          .map(convert_ts_type)
          .collect::<Result<Vec<_>, _>>()
      })
      .transpose()?;
    for candidate in candidates {
      let Type::Function(parameters, return_type) = candidate else {
        continue;
      };
      if !parameters.is_empty() && parameters.len() != arguments.len() {
        continue;
      }
      let mut environment = TypeEnvironment::new();
      let mut generic_names = Vec::new();
      for parameter in &parameters {
        collect_generic_names(parameter, &self.named_types, &mut generic_names);
      }
      collect_generic_names(&return_type, &self.named_types, &mut generic_names);
      if let Some(explicit_types) = &explicit_types {
        for (name, typ) in generic_names.iter().zip(explicit_types) {
          environment.insert(name.clone(), typ.clone());
        }
      }
      for (parameter, argument) in parameters.iter().zip(&arguments) {
        infer_type_parameter(parameter, argument, &mut environment);
      }
      for name in &generic_names {
        environment
          .entry(name.clone())
          .or_insert(Type::Never);
      }
      let mut compatible = true;
      for (parameter, argument) in parameters.iter().zip(&arguments) {
        let parameter = self.resolve_type_with_environment(parameter, &environment, 0);
        if !self.is_assignable(&parameter, &self.resolve_type(argument)) {
          compatible = false;
          break;
        }
      }
      if compatible {
        return Ok(self.resolve_type_with_environment(&return_type, &environment, 0));
      }
    }
    Err(TypeCheckerError::from(format!(
      "No overload matches call for {}",
      type_to_string(callee)
    )))
  }

  /// Returns the type of the given OAST expression.
  ///
  /// # Errors
  ///
  /// Returns a `TypeCheckerError` if the expression cannot be typechecked.
  #[allow(clippy::too_many_lines)]
  fn type_of_expr_oast(
    &mut self,
    expr: &oast::Expression,
  ) -> Result<Type, TypeCheckerError> {
    use oast::Expression as OExpr;
    match expr {
      OExpr::NumericLiteral(literal) => {
        Ok(Type::Literal(LiteralType::Number(literal.value.to_bits())))
      }
      OExpr::StringLiteral(literal) => Ok(Type::Literal(LiteralType::String(
        literal.value.to_string(),
      ))),
      OExpr::BooleanLiteral(literal) => Ok(Type::Literal(LiteralType::Boolean(literal.value))),
      OExpr::NullLiteral(_) => Ok(Type::Null),
      OExpr::Identifier(id) => {
        let name = id.name.as_str();
        self
          .lookup(name)
          .ok_or_else(|| TypeCheckerError::from(format!("Unknown identifier '{name}'")))
      }
      OExpr::UnaryExpression(u) => {
        let a = widen_literal(self.type_of_expr_oast(&u.argument)?);
        match u.operator {
          oast::UnaryOperator::LogicalNot => Ok(Type::Boolean),
          oast::UnaryOperator::Typeof => Ok(Type::String),
          oast::UnaryOperator::Void => Ok(Type::Void),
          oast::UnaryOperator::Delete => Ok(Type::Boolean),
          oast::UnaryOperator::UnaryPlus
          | oast::UnaryOperator::UnaryNegation
          | oast::UnaryOperator::BitwiseNot => {
            if self.is_assignable(&Type::Number, &a) {
              Ok(Type::Number)
            } else {
              Err(TypeCheckerError::from(
                "numeric unary operator requires number",
              ))
            }
          }
        }
      }
      OExpr::BinaryExpression(b) => {
        let l = widen_literal(self.type_of_expr_oast(&b.left)?);
        let r = widen_literal(self.type_of_expr_oast(&b.right)?);
        match b.operator {
          oast::BinaryOperator::Addition => {
            if matches!(l, Type::Any) || matches!(r, Type::Any) {
              Ok(Type::Any)
            } else if l == Type::Number && r == Type::Number {
              Ok(Type::Number)
            } else if l == Type::String || r == Type::String {
              Ok(Type::String)
            } else {
              Err(TypeCheckerError::from(format!(
                "Cannot add {} and {}",
                type_to_string(&l),
                type_to_string(&r)
              )))
            }
          }
          oast::BinaryOperator::Subtraction
          | oast::BinaryOperator::Multiplication
          | oast::BinaryOperator::Division
          | oast::BinaryOperator::Remainder
          | oast::BinaryOperator::Exponential
          | oast::BinaryOperator::ShiftLeft
          | oast::BinaryOperator::ShiftRight
          | oast::BinaryOperator::ShiftRightZeroFill
          | oast::BinaryOperator::BitwiseOR
          | oast::BinaryOperator::BitwiseXOR
          | oast::BinaryOperator::BitwiseAnd => {
            if self.is_assignable(&Type::Number, &l) && self.is_assignable(&Type::Number, &r) {
              Ok(Type::Number)
            } else {
              Err(TypeCheckerError::from(format!(
                "Arithmetic requires number, got {} and {}",
                type_to_string(&l),
                type_to_string(&r)
              )))
            }
          }
          oast::BinaryOperator::Equality
          | oast::BinaryOperator::Inequality
          | oast::BinaryOperator::StrictEquality
          | oast::BinaryOperator::StrictInequality
          | oast::BinaryOperator::LessThan
          | oast::BinaryOperator::LessEqualThan
          | oast::BinaryOperator::GreaterThan
          | oast::BinaryOperator::GreaterEqualThan
          | oast::BinaryOperator::In
          | oast::BinaryOperator::Instanceof => Ok(Type::Boolean),
        }
      }
      OExpr::AssignmentExpression(assignment) => {
        let actual = self.type_of_expr_oast(&assignment.right)?;
        if assignment.operator == oast::AssignmentOperator::Assign
          && let oast::AssignmentTarget::AssignmentTargetIdentifier(identifier) = &assignment.left
        {
          let name = identifier.name.as_str();
          if let Some(expected) = self.lookup(name)
            && !self.is_assignable(&expected, &actual)
          {
            return Err(TypeCheckerError::from(format!(
              "Type '{}' is not assignable to '{}' for variable '{}'",
              type_to_string(&actual),
              type_to_string(&expected),
              name
            )));
          }
        }
        Ok(actual)
      }
      OExpr::LogicalExpression(l) => {
        let left = self.type_of_expr_oast(&l.left)?;
        let right = self.type_of_expr_oast(&l.right)?;
        if self.is_assignable(&left, &right) {
          Ok(left)
        } else if self.is_assignable(&right, &left) {
          Ok(right)
        } else {
          Ok(Type::Union(vec![left, right]))
        }
      }
      OExpr::CallExpression(c) => {
        let callee_type = self.type_of_expr_oast(&c.callee)?;
        let is_console_log = if let OExpr::StaticMemberExpression(m) = &c.callee {
          if let OExpr::Identifier(obj_ident) = &m.object {
            let obj = obj_ident.name.as_str();
            obj == "console" && m.property.name.as_str() == "log"
          } else {
            false
          }
        } else {
          false
        };
        if is_console_log {
          return Ok(Type::Void);
        }
        match &callee_type {
          Type::Function(..) | Type::Union(_) => self.call_type(&callee_type, c),
          Type::Any => Ok(Type::Any),
          Type::Unknown => Err(TypeCheckerError::from("Cannot call unknown")),
          _ => Err(TypeCheckerError::from(format!(
            "Cannot call non-function type {}",
            type_to_string(&callee_type)
          ))),
        }
      }
      OExpr::StaticMemberExpression(m) => {
        let inferred_object_type = self.type_of_expr_oast(&m.object)?;
        let obj_type = if matches!(inferred_object_type, Type::Object(_)) {
          inferred_object_type
        } else {
          self.resolve_type(&inferred_object_type)
        };
        match obj_type {
          Type::Object(ref props) => {
            let key = m.property.name.to_string();
            if let Some(t) = props.get(&key) {
              Ok(t.clone())
            } else {
              Err(TypeCheckerError::from(format!(
                "Property '{}' does not exist on type object",
                key
              )))
            }
          }
          Type::Any => Ok(Type::Any),
          Type::Unknown => Err(TypeCheckerError::from(
            "Cannot read a property from unknown",
          )),
          _ => Err(TypeCheckerError::from(format!(
            "Property '{}' does not exist on type {}",
            m.property.name,
            type_to_string(&obj_type)
          ))),
        }
      }
      OExpr::ComputedMemberExpression(member) => {
        let inferred_object_type = self.type_of_expr_oast(&member.object)?;
        match self.resolve_type(&inferred_object_type) {
          Type::Array(element) => Ok(*element),
          Type::Any => Ok(Type::Any),
          _ => Err(TypeCheckerError::from(
            "Computed member requires an array or indexable object",
          )),
        }
      }
      OExpr::ArrayExpression(arr) => {
        if arr.elements.is_empty() {
          return Ok(Type::Array(Box::new(Type::Any)));
        }
        let first_expr = arr.elements[0]
          .as_expression()
          .ok_or_else(|| TypeCheckerError::from("Unsupported array element"))?;
        let first = widen_literal(self.type_of_expr_oast(first_expr)?);
        for e in &arr.elements[1..] {
          let expr = e
            .as_expression()
            .ok_or_else(|| TypeCheckerError::from("Unsupported array element"))?;
          let t = widen_literal(self.type_of_expr_oast(expr)?);
          if !self.is_assignable(&first, &t) && !self.is_assignable(&t, &first) {
            return Ok(Type::Array(Box::new(Type::Union(vec![first, t]))));
          }
        }
        Ok(Type::Array(Box::new(first)))
      }
      OExpr::ThisExpression(_) => Ok(Type::Object(HashMap::new())),
      OExpr::ObjectExpression(obj) => {
        let mut props = HashMap::new();
        for p in &obj.properties {
          if let oast::ObjectPropertyKind::ObjectProperty(prop) = p {
            if prop.computed {
              continue;
            }
            let t = self.type_of_expr_oast(&prop.value)?;
            match &prop.key {
              oast::PropertyKey::StaticIdentifier(ident) => {
                props.insert(ident.name.to_string(), t);
              }
              oast::PropertyKey::StringLiteral(s) => {
                props.insert(s.value.to_string(), t);
              }
              _ => {}
            }
          }
        }
        Ok(Type::Object(props))
      }
      OExpr::ParenthesizedExpression(p) => self.type_of_expr_oast(&p.expression),
      OExpr::TemplateLiteral(_) => Ok(Type::String),
      OExpr::ConditionalExpression(expression) => {
        drop(self.type_of_expr_oast(&expression.test)?);
        let consequent = self.type_of_expr_oast(&expression.consequent)?;
        let alternate = self.type_of_expr_oast(&expression.alternate)?;
        if self.is_assignable(&consequent, &alternate) {
          Ok(consequent)
        } else if self.is_assignable(&alternate, &consequent) {
          Ok(alternate)
        } else {
          Ok(Type::Union(vec![consequent, alternate]))
        }
      }
      OExpr::TSAsExpression(expression) => convert_ts_type(&expression.type_annotation),
      OExpr::TSTypeAssertion(expression) => convert_ts_type(&expression.type_annotation),
      OExpr::TSNonNullExpression(expression) => self.type_of_expr_oast(&expression.expression),
      OExpr::FunctionExpression(function) => {
        let typ = self.function_type(&function.params, function.return_type.as_deref())?;
        self.check_function(function)?;
        Ok(typ)
      }
      OExpr::ArrowFunctionExpression(function) => {
        self.function_type(&function.params, function.return_type.as_deref())
      }
      _ => Err(TypeCheckerError::from(
        "Unsupported expression in type checker",
      )),
    }
  }
}

/// Converts an OAST `TSTypeAnnotation` into a `Type` value.
///
/// # Errors
///
/// Returns a `TypeCheckerError` if the type cannot be converted.
fn convert_type_ann(ty: &oast::TSTypeAnnotation<'_>) -> Result<Type, TypeCheckerError> {
  convert_ts_type(&ty.type_annotation)
}

/// Converts an OAST `TSType` into a `Type` value.
///
/// # Errors
///
/// Returns a `TypeCheckerError` if the type cannot be converted.
fn convert_ts_type(ty: &oast::TSType<'_>) -> Result<Type, TypeCheckerError> {
  use oast::TSType::*;

  match ty {
    TSNeverKeyword(_) => Ok(Type::Never),
    TSNumberKeyword(_) => Ok(Type::Number),
    TSStringKeyword(_) => Ok(Type::String),
    TSBooleanKeyword(_) => Ok(Type::Boolean),
    TSNullKeyword(_) => Ok(Type::Null),
    TSUndefinedKeyword(_) => Ok(Type::Undefined),
    TSVoidKeyword(_) => Ok(Type::Void),
    TSAnyKeyword(_) => Ok(Type::Any),
    TSUnknownKeyword(_) => Ok(Type::Unknown),
    TSObjectKeyword(_) => Ok(Type::Object(HashMap::new())),
    TSArrayType(t) => Ok(Type::Array(Box::new(convert_ts_type(&t.element_type)?))),
    TSParenthesizedType(t) => convert_ts_type(&t.type_annotation),
    TSTypeReference(reference) => match &reference.type_name {
      oast::TSTypeName::IdentifierReference(identifier) => Ok(Type::TypeReference {
        name: identifier.name.to_string(),
        arguments: reference
          .type_arguments
          .as_ref()
          .map(|arguments| {
            arguments
              .params
              .iter()
              .map(convert_ts_type)
              .collect::<Result<Vec<_>, _>>()
          })
          .transpose()?
          .unwrap_or_default(),
      }),
      oast::TSTypeName::QualifiedName(qualified) => Ok(Type::TypeReference {
        name: qualified_type_name(&qualified.left, qualified.right.name.as_str()),
        arguments: reference
          .type_arguments
          .as_ref()
          .map(|arguments| {
            arguments
              .params
              .iter()
              .map(convert_ts_type)
              .collect::<Result<Vec<_>, _>>()
          })
          .transpose()?
          .unwrap_or_default(),
      }),
      oast::TSTypeName::ThisExpression(_) => Ok(Type::TypeReference {
        name: "this".to_string(),
        arguments: Vec::new(),
      }),
    },
    TSConditionalType(conditional) => Ok(Type::Conditional {
      distributive_parameter: naked_type_parameter_name(&conditional.check_type),
      check: Box::new(convert_ts_type(&conditional.check_type)?),
      extends: Box::new(convert_ts_type(&conditional.extends_type)?),
      true_type: Box::new(convert_ts_type(&conditional.true_type)?),
      false_type: Box::new(convert_ts_type(&conditional.false_type)?),
    }),
    TSIntersectionType(intersection) => Ok(Type::Intersection(
      intersection
        .types
        .iter()
        .map(convert_ts_type)
        .collect::<Result<Vec<_>, _>>()?,
    )),
    TSLiteralType(literal) => convert_literal_type(&literal.literal),
    TSTupleType(tuple) => Ok(Type::Tuple(
      tuple
        .element_types
        .iter()
        .map(convert_tuple_element)
        .collect::<Result<Vec<_>, _>>()?,
    )),
    TSTypeOperatorType(operator) => {
      let operand = convert_ts_type(&operator.type_annotation)?;
      if operator.operator == oast::TSTypeOperatorOperator::Keyof {
        Ok(Type::KeyOf(Box::new(operand)))
      } else {
        Ok(operand)
      }
    }
    TSIndexedAccessType(access) => Ok(Type::IndexedAccess {
      object: Box::new(convert_ts_type(&access.object_type)?),
      index: Box::new(convert_ts_type(&access.index_type)?),
    }),
    TSInferType(infer) => Ok(Type::Infer(infer.type_parameter.name.name.to_string())),
    TSMappedType(mapped) => Ok(Type::Mapped {
      parameter: mapped.key.name.to_string(),
      constraint: Box::new(convert_ts_type(&mapped.constraint)?),
      value: Box::new(
        mapped
          .type_annotation
          .as_ref()
          .map(convert_ts_type)
          .transpose()?
          .unwrap_or(Type::Unknown),
      ),
    }),
    TSTemplateLiteralType(template) => Ok(Type::TemplateLiteral {
      quasis: template
        .quasis
        .iter()
        .map(|quasi| {
          quasi
            .value
            .cooked
            .as_ref()
            .unwrap_or(&quasi.value.raw)
            .to_string()
        })
        .collect(),
      substitutions: template
        .types
        .iter()
        .map(convert_ts_type)
        .collect::<Result<Vec<_>, _>>()?,
    }),
    TSTypeLiteral(literal) => signatures_to_object(&literal.members),
    TSFunctionType(function) => Ok(Type::Function(
      parameter_types(&function.params)?,
      Box::new(convert_type_ann(&function.return_type)?),
    )),
    TSUnionType(u) => {
      let mut variants = Vec::new();
      for member in &u.types {
        variants.push(convert_ts_type(member)?);
      }
      Ok(Type::Union(variants))
    }
    _ => Ok(Type::Unknown),
  }
}

fn type_definition(
  parameters: Option<&oast::TSTypeParameterDeclaration<'_>>,
  body: &oast::TSType<'_>,
) -> Result<TypeDefinition, TypeCheckerError> {
  Ok(TypeDefinition {
    parameters: convert_type_parameters(parameters)?,
    body: convert_ts_type(body)?,
  })
}

fn convert_type_parameters(
  declaration: Option<&oast::TSTypeParameterDeclaration<'_>>
) -> Result<Vec<TypeParameter>, TypeCheckerError> {
  declaration.map_or_else(
    || Ok(Vec::new()),
    |declaration| {
      declaration
        .params
        .iter()
        .map(|parameter| {
          Ok(TypeParameter {
            name: parameter.name.name.to_string(),
            constraint: parameter
              .constraint
              .as_ref()
              .map(convert_ts_type)
              .transpose()?,
            default: parameter
              .default
              .as_ref()
              .map(convert_ts_type)
              .transpose()?,
          })
        })
        .collect()
    },
  )
}

fn naked_type_parameter_name(typ: &oast::TSType<'_>) -> Option<String> {
  if let oast::TSType::TSTypeReference(reference) = typ
    && reference.type_arguments.is_none()
    && let oast::TSTypeName::IdentifierReference(identifier) = &reference.type_name
  {
    return Some(identifier.name.to_string());
  }
  None
}

fn convert_literal_type(literal: &oast::TSLiteral<'_>) -> Result<Type, TypeCheckerError> {
  match literal {
    oast::TSLiteral::BooleanLiteral(literal) => {
      Ok(Type::Literal(LiteralType::Boolean(literal.value)))
    }
    oast::TSLiteral::NumericLiteral(literal) => {
      Ok(Type::Literal(LiteralType::Number(literal.value.to_bits())))
    }
    oast::TSLiteral::StringLiteral(literal) => Ok(Type::Literal(LiteralType::String(
      literal.value.to_string(),
    ))),
    _ => Ok(Type::Unknown),
  }
}

fn convert_tuple_element(element: &oast::TSTupleElement<'_>) -> Result<Type, TypeCheckerError> {
  match element {
    oast::TSTupleElement::TSOptionalType(optional) => Ok(normalize_union(vec![
      convert_ts_type(&optional.type_annotation)?,
      Type::Undefined,
    ])),
    oast::TSTupleElement::TSRestType(rest) => Ok(Type::Rest(Box::new(convert_ts_type(
      &rest.type_annotation,
    )?))),
    oast::TSTupleElement::TSNamedTupleMember(named) => {
      let typ = convert_tuple_element(&named.element_type)?;
      if named.optional {
        Ok(normalize_union(vec![typ, Type::Undefined]))
      } else {
        Ok(typ)
      }
    }
    _ => element
      .as_ts_type()
      .map(convert_ts_type)
      .unwrap_or_else(|| Ok(Type::Unknown)),
  }
}

fn normalize_union(types: Vec<Type>) -> Type {
  let mut normalized = Vec::new();
  for typ in types {
    match typ {
      Type::Never => {}
      Type::Union(members) => {
        for member in members {
          if !normalized.contains(&member) {
            normalized.push(member);
          }
        }
      }
      other if !normalized.contains(&other) => normalized.push(other),
      _ => {}
    }
  }
  match normalized.len() {
    0 => Type::Never,
    1 => normalized.pop().unwrap_or(Type::Never),
    _ => Type::Union(normalized),
  }
}

fn union_members(typ: Type) -> Vec<Type> {
  match typ {
    Type::Union(members) => members,
    Type::Never => Vec::new(),
    other => vec![other],
  }
}

fn property_key_from_type(typ: &Type) -> Option<String> {
  match typ {
    Type::Literal(LiteralType::String(value)) => Some(value.clone()),
    Type::Literal(LiteralType::Number(bits)) => Some(f64::from_bits(*bits).to_string()),
    _ => None,
  }
}

fn template_substitution_values(typ: &Type) -> Option<Vec<String>> {
  match typ {
    Type::Literal(LiteralType::String(value)) => Some(vec![value.clone()]),
    Type::Literal(LiteralType::Number(bits)) => Some(vec![f64::from_bits(*bits).to_string()]),
    Type::Literal(LiteralType::Boolean(value)) => Some(vec![value.to_string()]),
    Type::Boolean => Some(vec!["true".to_string(), "false".to_string()]),
    Type::Union(members) => {
      let mut values = Vec::new();
      for member in members {
        values.extend(template_substitution_values(member)?);
      }
      Some(values)
    }
    _ => None,
  }
}

fn evaluate_template_literal(
  quasis: &[String],
  substitutions: &[Type],
) -> Type {
  const EXPANSION_LIMIT: usize = 4096;

  let mut values = vec![quasis.first().cloned().unwrap_or_default()];
  for (index, substitution) in substitutions.iter().enumerate() {
    let Some(parts) = template_substitution_values(substitution) else {
      return Type::String;
    };
    if values.len().saturating_mul(parts.len()) > EXPANSION_LIMIT {
      return Type::String;
    }
    let suffix = quasis.get(index + 1).cloned().unwrap_or_default();
    values = values
      .into_iter()
      .flat_map(|prefix| {
        parts
          .iter()
          .map(|part| format!("{}{}{}", prefix, part, suffix))
          .collect::<Vec<_>>()
      })
      .collect();
  }
  normalize_union(
    values
      .into_iter()
      .map(|value| Type::Literal(LiteralType::String(value)))
      .collect(),
  )
}

fn widen_literal(typ: Type) -> Type {
  match typ {
    Type::Literal(LiteralType::String(_)) => Type::String,
    Type::Literal(LiteralType::Number(_)) => Type::Number,
    Type::Literal(LiteralType::Boolean(_)) => Type::Boolean,
    other => other,
  }
}

fn collect_generic_names(
  typ: &Type,
  named_types: &HashMap<String, TypeDefinition>,
  names: &mut Vec<String>,
) {
  match typ {
    Type::TypeReference { name, arguments } => {
      if arguments.is_empty()
        && !name.contains('.')
        && !named_types.contains_key(name)
        && !names.contains(name)
      {
        names.push(name.clone());
      }
      for argument in arguments {
        collect_generic_names(argument, named_types, names);
      }
    }
    Type::Array(element) | Type::Rest(element) => {
      collect_generic_names(element, named_types, names)
    }
    Type::Tuple(elements) | Type::Union(elements) | Type::Intersection(elements) => {
      for element in elements {
        collect_generic_names(element, named_types, names);
      }
    }
    Type::Object(properties) => {
      for property in properties.values() {
        collect_generic_names(property, named_types, names);
      }
    }
    Type::Function(parameters, return_type) => {
      for parameter in parameters {
        collect_generic_names(parameter, named_types, names);
      }
      collect_generic_names(return_type, named_types, names);
    }
    _ => {}
  }
}

fn infer_type_parameter(
  parameter: &Type,
  actual: &Type,
  environment: &mut TypeEnvironment,
) {
  match parameter {
    Type::TypeReference { name, arguments } if arguments.is_empty() => {
      environment
        .entry(name.clone())
        .or_insert_with(|| actual.clone());
    }
    Type::TypeReference { name, arguments } => {
      if let Type::TypeReference {
        name: actual_name,
        arguments: actual_arguments,
      } = actual
        && name.rsplit('.').next() == actual_name.rsplit('.').next()
      {
        for (parameter, actual) in arguments.iter().zip(actual_arguments) {
          infer_type_parameter(parameter, actual, environment);
        }
      }
    }
    Type::Array(parameter) => match actual {
      Type::Array(actual) => infer_type_parameter(parameter, actual, environment),
      Type::Tuple(actual) => {
        for actual in actual {
          infer_type_parameter(parameter, actual, environment);
        }
      }
      _ => {}
    },
    Type::Object(properties) => {
      if let Type::Object(actual) = actual {
        for (name, parameter) in properties {
          if let Some(actual) = actual.get(name) {
            infer_type_parameter(parameter, actual, environment);
          }
        }
      }
    }
    Type::Function(parameters, return_type) => {
      if let Type::Function(actual_parameters, actual_return_type) = actual {
        for (parameter, actual) in parameters.iter().zip(actual_parameters) {
          infer_type_parameter(parameter, actual, environment);
        }
        infer_type_parameter(return_type, actual_return_type, environment);
      }
    }
    _ => {}
  }
}

fn resolve_indexed_access(
  object: &Type,
  index: &Type,
) -> Type {
  if let Type::Union(indices) = index {
    return normalize_union(
      indices
        .iter()
        .map(|index| resolve_indexed_access(object, index))
        .collect(),
    );
  }
  match (object, index) {
    (Type::Object(properties), Type::Literal(LiteralType::String(key))) => properties
      .get(key)
      .cloned()
      .unwrap_or(Type::Never),
    (Type::Array(element), Type::Number | Type::Literal(LiteralType::Number(_))) => {
      (**element).clone()
    }
    (Type::Tuple(elements), Type::Literal(LiteralType::Number(bits))) => {
      let index = f64::from_bits(*bits);
      if index.fract() == 0.0 && index >= 0.0 {
        elements
          .get(index as usize)
          .cloned()
          .unwrap_or(Type::Never)
      } else {
        Type::Never
      }
    }
    (Type::Tuple(elements), Type::Number) => normalize_union(elements.clone()),
    _ => Type::Unknown,
  }
}

fn is_optional_type(typ: &Type) -> bool {
  match typ {
    Type::Union(types) => types
      .iter()
      .any(|typ| matches!(typ, Type::Undefined)),
    _ => false,
  }
}

fn assignable(
  expected: &Type,
  actual: &Type,
) -> bool {
  match (expected, actual) {
    (_, Type::Never) => true,
    (Type::Never, _) => false,
    (Type::Any, _) | (_, Type::Any) => true,
    (Type::Unknown, _) => true,
    (_, Type::Unknown) => false,
    (Type::Number, Type::Number) => true,
    (Type::String, Type::String) => true,
    (Type::Boolean, Type::Boolean) => true,
    (Type::Number, Type::Literal(LiteralType::Number(_))) => true,
    (Type::String, Type::Literal(LiteralType::String(_))) => true,
    (Type::Boolean, Type::Literal(LiteralType::Boolean(_))) => true,
    (Type::Literal(expected), Type::Literal(actual)) => expected == actual,
    (Type::Null, Type::Null) => true,
    (Type::Undefined, Type::Undefined) => true,
    (Type::Void, Type::Void) => true,
    (Type::Array(a), Type::Array(b)) => assignable(a, b),
    (Type::Tuple(a), Type::Tuple(b)) => {
      a.len() == b.len()
        && a
          .iter()
          .zip(b.iter())
          .all(|(expected, actual)| assignable(expected, actual))
    }
    (Type::Array(expected), Type::Tuple(actual)) => actual
      .iter()
      .all(|actual| assignable(expected, actual)),
    (Type::Object(a), Type::Object(b)) => {
      for (k, t) in a {
        if let Some(t2) = b.get(k) {
          if !assignable(t, t2) {
            return false;
          }
        } else if !is_optional_type(t) {
          return false;
        }
      }
      true
    }
    (Type::Function(a, a_return), Type::Function(b, b_return)) => {
      // Unannotated source callbacks are intentionally represented as Any;
      // their bodies are not inferred by this lightweight checker.
      if matches!(b_return.as_ref(), Type::Any) {
        return true;
      }
      a.len() == b.len()
        && a
          .iter()
          .zip(b.iter())
          .all(|(expected, actual)| assignable(expected, actual))
        && assignable(a_return, b_return)
    }
    (Type::Union(types), actual) => types
      .iter()
      .any(|expected| assignable(expected, actual)),
    (expected, Type::Union(types)) => types
      .iter()
      .all(|actual| assignable(expected, actual)),
    (Type::Intersection(types), actual) => types
      .iter()
      .all(|expected| assignable(expected, actual)),
    _ => false,
  }
}

fn parameter_types(params: &oast::FormalParameters<'_>) -> Result<Vec<Type>, TypeCheckerError> {
  let mut types = Vec::new();
  for parameter in &params.items {
    types.push(
      parameter
        .type_annotation
        .as_deref()
        .map(convert_type_ann)
        .transpose()?
        .unwrap_or(Type::Unknown),
    );
  }
  if let Some(rest) = &params.rest {
    types.push(
      rest
        .type_annotation
        .as_deref()
        .map(convert_type_ann)
        .transpose()?
        .unwrap_or(Type::Unknown),
    );
  }
  Ok(types)
}

fn qualified_type_name(
  left: &oast::TSTypeName<'_>,
  right: &str,
) -> String {
  let left = match left {
    oast::TSTypeName::IdentifierReference(name) => name.name.to_string(),
    oast::TSTypeName::QualifiedName(name) => {
      qualified_type_name(&name.left, name.right.name.as_str())
    }
    oast::TSTypeName::ThisExpression(_) => "this".to_string(),
  };
  format!("{left}.{right}")
}

fn module_export_name(name: &oast::ModuleExportName<'_>) -> Result<String, TypeCheckerError> {
  match name {
    oast::ModuleExportName::IdentifierName(name) => Ok(name.name.to_string()),
    oast::ModuleExportName::IdentifierReference(name) => Ok(name.name.to_string()),
    oast::ModuleExportName::StringLiteral(name) => Ok(name.value.to_string()),
  }
}

fn module_namespace_values(module: &ModuleType) -> HashMap<String, Type> {
  let mut values = module.values.clone();
  for (name, namespace) in &module.namespaces {
    values.insert(
      name.clone(),
      Type::Object(module_namespace_values(namespace)),
    );
  }
  values
}

fn register_namespace_types(
  prefix: &str,
  module: &ModuleType,
  namespace_types: &mut HashMap<String, TypeDefinition>,
) {
  for (name, definition) in &module.types {
    namespace_types.insert(format!("{prefix}.{name}"), definition.clone());
  }
  for (name, nested) in &module.namespaces {
    register_namespace_types(&format!("{prefix}.{name}"), nested, namespace_types);
  }
}

fn merge_callable(
  values: &mut HashMap<String, Type>,
  name: &str,
  typ: Type,
) {
  if let Some(existing) = values.remove(name) {
    values.insert(name.to_string(), Type::Union(vec![existing, typ]));
  } else {
    values.insert(name.to_string(), typ);
  }
}

fn merge_callable_scope(
  scope: &mut Scope,
  name: &str,
  typ: Type,
) {
  if let Some(existing) = scope.remove(name) {
    scope.insert(name.to_string(), Type::Union(vec![existing, typ]));
  } else {
    scope.insert(name.to_string(), typ);
  }
}

fn property_name(key: &oast::PropertyKey<'_>) -> Option<String> {
  match key {
    oast::PropertyKey::StaticIdentifier(identifier) => Some(identifier.name.to_string()),
    oast::PropertyKey::StringLiteral(literal) => Some(literal.value.to_string()),
    _ => None,
  }
}

fn function_type_from_call_signature(
  call: &oast::TSCallSignatureDeclaration<'_>
) -> Result<Type, TypeCheckerError> {
  let parameters = parameter_types(&call.params)?;
  let return_type = call
    .return_type
    .as_deref()
    .map(convert_type_ann)
    .transpose()?
    .unwrap_or(Type::Unknown);
  Ok(Type::Function(parameters, Box::new(return_type)))
}

fn signatures_to_object(signatures: &[oast::TSSignature<'_>]) -> Result<Type, TypeCheckerError> {
  let mut properties = HashMap::new();
  let mut call_signatures = Vec::new();
  for signature in signatures {
    match signature {
      oast::TSSignature::TSPropertySignature(property) => {
        if let Some(name) = property_name(&property.key) {
          let typ = property
            .type_annotation
            .as_deref()
            .map(convert_type_ann)
            .transpose()?
            .unwrap_or(Type::Unknown);
          properties.insert(name, typ);
        }
      }
      oast::TSSignature::TSMethodSignature(method) => {
        if let Some(name) = property_name(&method.key) {
          let return_type = method
            .return_type
            .as_deref()
            .map(convert_type_ann)
            .transpose()?
            .unwrap_or(Type::Unknown);
          properties.insert(
            name,
            Type::Function(parameter_types(&method.params)?, Box::new(return_type)),
          );
        }
      }
      oast::TSSignature::TSCallSignatureDeclaration(call) => {
        call_signatures.push(function_type_from_call_signature(call)?);
      }
      _ => {}
    }
  }
  if !call_signatures.is_empty() {
    if properties.is_empty() {
      return Ok(normalize_union(call_signatures));
    }
    properties.insert("[[call]]".to_string(), normalize_union(call_signatures));
  }
  Ok(Type::Object(properties))
}

/// Render a human-readable name for a checker `Type`.
pub fn type_to_string(t: &Type) -> String {
  match t {
    Type::Never => "never".to_string(),
    Type::Number => "number".to_string(),
    Type::String => "string".to_string(),
    Type::Boolean => "boolean".to_string(),
    Type::Null => "null".to_string(),
    Type::Undefined => "undefined".to_string(),
    Type::Void => "void".to_string(),
    Type::Any => "any".to_string(),
    Type::Unknown => "unknown".to_string(),
    Type::Array(inner) => format!("{}[]", type_to_string(inner)),
    Type::Tuple(elements) => format!(
      "[{}]",
      elements
        .iter()
        .map(type_to_string)
        .collect::<Vec<_>>()
        .join(", ")
    ),
    Type::Rest(element) => format!("...{}", type_to_string(element)),
    Type::Object(_) => "object".to_string(),
    Type::Function(params, ret) => format!(
      "fn({}) -> {}",
      params
        .iter()
        .map(type_to_string)
        .collect::<Vec<_>>()
        .join(", "),
      type_to_string(ret)
    ),
    Type::TypeReference { name, arguments } => {
      if arguments.is_empty() {
        name.clone()
      } else {
        format!(
          "{}<{}>",
          name,
          arguments
            .iter()
            .map(type_to_string)
            .collect::<Vec<_>>()
            .join(", ")
        )
      }
    }
    Type::Union(v) => v
      .iter()
      .map(type_to_string)
      .collect::<Vec<_>>()
      .join(" | "),
    Type::Intersection(v) => v
      .iter()
      .map(type_to_string)
      .collect::<Vec<_>>()
      .join(" & "),
    Type::Literal(LiteralType::String(value)) => format!("{:?}", value),
    Type::Literal(LiteralType::Number(bits)) => f64::from_bits(*bits).to_string(),
    Type::Literal(LiteralType::Boolean(value)) => value.to_string(),
    Type::Conditional { .. } => "conditional type".to_string(),
    Type::KeyOf(object) => format!("keyof {}", type_to_string(object)),
    Type::IndexedAccess { object, index } => {
      format!("{}[{}]", type_to_string(object), type_to_string(index))
    }
    Type::Infer(name) => format!("infer {}", name),
    Type::Mapped { parameter, .. } => format!("{{ [{} in ...]: ... }}", parameter),
    Type::TemplateLiteral { .. } => "template literal type".to_string(),
    Type::Builtin(b) => format!("builtin::{:?}", b),
  }
}

