thread_local! {
    static STRICT_OVERRIDE: std::cell::RefCell<Option<bool>> = const { std::cell::RefCell::new(None) };
}

/// Return whether strict mode is currently enabled.
///
/// The checker consults this flag when deciding whether unannotated parameters
/// should produce implicit-`any` diagnostics. The effective strictness is
/// determined by, in order:
/// 1. The test-only override set via `set_strict_override(Some(bool))`.
/// 2. The environment variable `TSBLITZ_STRICT` (any value other than `0`
///    enables strict mode).
/// 3. Defaults to disabled when the environment variable is not set.
fn strict_mode() -> bool {
  if let Some(v) = STRICT_OVERRIDE.with(|m| *m.borrow()) {
    return v;
  }
  std::env::var("TSBLITZ_STRICT").is_ok_and(|v| v != "0")
}

/// Override strict-mode behavior for type checking.
///
/// Passing `Some(true)` or `Some(false)` forces strict mode on or off.
/// Passing `None` clears the override and restores environment-driven behavior.
///
/// # Panics
/// Panics if the thread-local override is already borrowed.
pub fn set_strict_override(v: Option<bool>) {
  STRICT_OVERRIDE.with(|m| {
    *m.borrow_mut() = v;
  });
}

/// Return the current thread-local strict override, if any.
pub(crate) fn strict_override() -> Option<bool> {
  STRICT_OVERRIDE.with(|m| *m.borrow())
}

/// Temporarily set the thread-local strict override while running `f`.
pub fn with_strict_override<R>(
  v: Option<bool>,
  f: impl FnOnce() -> R,
) -> R {
  struct ResetStrict(Option<bool>);

  impl Drop for ResetStrict {
    fn drop(&mut self) {
      set_strict_override(self.0);
    }
  }

  let previous = strict_override();
  set_strict_override(v);
  let _reset = ResetStrict(previous);
  f()
}

/// Run static type checking for a parsed program.
///
/// # Errors
/// Returns a `TypeCheckerError` if type checking fails.
pub fn check(program: &oast::Program<'_>) -> Result<(), TypeCheckerError> {
  check_with_declarations(program, &[])
}

/// A declaration source associated with a public virtual module.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct VirtualDeclaration {
  /// Canonical module specifier used by imports.
  pub specifier: String,
  /// TypeScript declaration source for the module.
  pub source: String,
}

/// The kind of annotation represented by a compiler inlay hint.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TypeInlayHintKind {
  /// A type annotation inferred for a binding or callback parameter.
  Type,
  /// A parameter name inferred from the selected call signature.
  Parameter,
}

/// A compiler-inferred annotation suitable for an editor inlay hint.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TypeInlayHint {
  /// UTF-8 byte position where the hint is inserted.
  pub position: usize,
  /// TypeScript annotation text, including the leading colon.
  pub label: String,
  /// Whether this is a type annotation or a parameter name.
  pub kind: TypeInlayHintKind,
}

/// Check a program against declarations retained by public virtual modules.
pub fn check_with_declarations(
  program: &oast::Program<'_>,
  declarations: &[VirtualDeclaration],
) -> Result<(), TypeCheckerError> {
  check_with_declarations_and_source_imports(program, declarations, &[])
}

/// Check a program against virtual declarations and imports resolved as source
/// modules by the module loader.
///
/// Source-module imports have no declaration model in this checker. They are
/// registered as `Unknown` bindings so they do not become declaration-module
/// lookups or silently acquire `Any` types. Imports whose source is neither a
/// supplied declaration nor a loader-confirmed source module remain strict
/// errors.
pub fn check_with_declarations_and_source_imports(
  program: &oast::Program<'_>,
  declarations: &[VirtualDeclaration],
  source_imports: &[String],
) -> Result<(), TypeCheckerError> {
  check_and_inlay_hints_with_declarations(program, declarations, source_imports).0
}

/// Check a program and retain contextual parameter types inferred by the compiler.
pub fn check_and_inlay_hints_with_declarations(
  program: &oast::Program<'_>,
  declarations: &[VirtualDeclaration],
  source_imports: &[String],
) -> (Result<(), TypeCheckerError>, Vec<TypeInlayHint>) {
  let mut ctx = TypeContext {
    scopes: vec![Scope::new()],
    named_types: HashMap::new(),
    modules: HashMap::new(),
    namespace_types: HashMap::new(),
    source_imports: source_imports.iter().cloned().collect(),
    check_imports: !declarations.is_empty() || !source_imports.is_empty(),
    expected_returns: Vec::new(),
    return_types: Vec::new(),
    inlay_hints: Vec::new(),
    function_parameter_metadata: HashMap::new(),
  };

  // Runtime globals with stable, useful surface types.
  ctx
    .scope_mut()
    .insert("undefined".to_string(), Type::Undefined);
  ctx
    .scope_mut()
    .insert("NaN".to_string(), Type::Number);
  ctx
    .scope_mut()
    .insert("Infinity".to_string(), Type::Number);
  ctx.scope_mut().insert(
    "isNaN".to_string(),
    Type::Function(vec![Type::Number], Box::new(Type::Boolean)),
  );
  ctx.scope_mut().insert(
    "isFinite".to_string(),
    Type::Function(vec![Type::Number], Box::new(Type::Boolean)),
  );
  ctx.scope_mut().insert(
    "parseInt".to_string(),
    Type::Function(vec![Type::String], Box::new(Type::Number)),
  );
  ctx.scope_mut().insert(
    "parseFloat".to_string(),
    Type::Function(vec![Type::String], Box::new(Type::Number)),
  );
  for name in [
    "decodeURI",
    "decodeURIComponent",
    "encodeURI",
    "encodeURIComponent",
    "eval",
  ] {
    ctx
      .scope_mut()
      .insert(name.to_string(), Type::Any);
  }
  ctx.scope_mut().insert(
    "console".to_string(),
    Type::Object(HashMap::from([(
      "log".to_string(),
      Type::Function(Vec::new(), Box::new(Type::Void)),
    )])),
  );
  ctx
    .scope_mut()
    .insert("process".to_string(), Type::Any);
  for name in [
    "Array",
    "ArrayBuffer",
    "Atomics",
    "BigInt",
    "BigInt64Array",
    "BigUint64Array",
    "Boolean",
    "DataView",
    "Date",
    "Error",
    "EvalError",
    "Function",
    "JSON",
    "Map",
    "Math",
    "Number",
    "Object",
    "Promise",
    "Proxy",
    "RangeError",
    "ReferenceError",
    "Reflect",
    "RegExp",
    "Set",
    "SharedArrayBuffer",
    "ShadowRealm",
    "String",
    "Symbol",
    "SyntaxError",
    "TypeError",
    "URIError",
    "Uint8Array",
    "Uint8ClampedArray",
    "Uint16Array",
    "Uint32Array",
    "Int8Array",
    "Int16Array",
    "Int32Array",
    "Float32Array",
    "Float64Array",
    "FinalizationRegistry",
    "WeakMap",
    "WeakRef",
    "WeakSet",
  ] {
    ctx
      .scope_mut()
      .insert(name.to_string(), Type::Any);
  }

  let result = (|| {
    ctx.register_declarations_sources(declarations)?;

    for stmt in &program.body {
      ctx.register_declarations(stmt)?;
    }

    for stmt in &program.body {
      ctx.check_statement_oast(stmt)?;
    }
    Ok(())
  })();
  ctx.inlay_hints.sort_by(|left, right| {
    left
      .position
      .cmp(&right.position)
      .then_with(|| left.label.cmp(&right.label))
  });
  ctx
    .inlay_hints
    .dedup_by(|left, right| left.position == right.position && left.label == right.label);
  (result, ctx.inlay_hints)
}

struct TypeContext {
  scopes: Vec<Scope>,
  named_types: HashMap<String, TypeDefinition>,
  modules: HashMap<String, ModuleType>,
  namespace_types: HashMap<String, TypeDefinition>,
  source_imports: HashSet<String>,
  check_imports: bool,
  expected_returns: Vec<Type>,
  return_types: Vec<Vec<Type>>,
  inlay_hints: Vec<TypeInlayHint>,
  /// Parameter names are kept beside `Type::Function` rather than inside it.
  ///
  /// `Type::Function` is also encoded by the bytecode bundle, so adding names
  /// to that enum would require a format migration. This sidecar intentionally
  /// has conservative limits: names survive ordinary declaration, method, and
  /// function-type construction, but two overloads with identical type text
  /// cannot be distinguished by metadata alone.
  function_parameter_metadata: HashMap<String, FunctionParameterMetadata>,
}

