use crate::bytecode::{Chunk, Instruction, Opcode, decode_aux16};

pub(super) fn opcode(word: u32) -> Opcode {
  unsafe { Instruction::decode_unchecked(word).opcode }
}

pub(super) fn number_constant(
  code: &Chunk,
  word: u32,
) -> Option<f64> {
  match code.constants.get(decode_aux16(word) as usize) {
    Some(crate::bytecode::Constant::Number(value)) => Some(*value),
    _ => None,
  }
}

