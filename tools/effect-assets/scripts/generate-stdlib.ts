import { dirname, join, relative, resolve } from "node:path";
import { existsSync, mkdirSync, readFileSync, renameSync, rmSync, statSync, writeFileSync } from "node:fs";

import { STDLIB_INPUTS, EFFECT_VERSION, HOST_ABI_VERSION, RUNTIME_ABI_VERSION, STDLIB_FORMAT_VERSION, STDLIB_VERSION } from "../src/stdlib-manifest.ts";
import { DEFAULT_OUTPUT, EFFECT_ASSETS, normalize, sha256, staticImports, type StdlibEntry, type StdlibManifest } from "./stdlib.ts";

const OUTPUT = resolve(process.env.BLITZ_STDLIB_OUTPUT ?? DEFAULT_OUTPUT);
const SOURCE_ROOT = resolve(import.meta.dirname, "../src");
const EFFECT_MANIFEST = JSON.parse(readFileSync(join(EFFECT_ASSETS, "manifest.json"), "utf8")) as {
  readonly package: { readonly name: string; readonly version: string };
  readonly entries: readonly { readonly specifier: string }[];
};

const writeText = (root: string, path: string, content: string) => {
  const destination = join(root, path);
  mkdirSync(dirname(destination), { recursive: true });
  writeFileSync(destination, normalize(content), "utf8");
};

const main = () => {
  if (EFFECT_MANIFEST.package.name !== "effect" || EFFECT_MANIFEST.package.version !== EFFECT_VERSION) throw new Error("the pinned Effect manifest is not available");
  const known = new Set([...EFFECT_MANIFEST.entries.map(entry => entry.specifier), ...STDLIB_INPUTS.map(entry => entry.specifier)]);
  const temp = `${OUTPUT}.tmp-${process.pid}`;
  rmSync(temp, { recursive: true, force: true });
  mkdirSync(temp, { recursive: true });

  const entries: StdlibEntry[] = [];
  const files: { path: string; sha256: string }[] = [];
  for (const input of STDLIB_INPUTS) {
    const sourcePath = resolve(SOURCE_ROOT, input.source);
    if (!sourcePath.startsWith(`${SOURCE_ROOT}/`) || !existsSync(sourcePath)) throw new Error(`missing stdlib source: ${input.source}`);
    const source = normalize(readFileSync(sourcePath, "utf8"));
    const sourceAsset = `modules/${input.source}`;
    const sourceReference = { path: sourceAsset, sha256: sha256(source) };
    writeText(temp, sourceAsset, source);
    files.push(sourceReference);

    const dependencies = [...new Set(staticImports(source, sourceAsset))];
    for (const dependency of dependencies) if (!known.has(dependency)) throw new Error(`unresolved stdlib dependency: ${input.specifier} -> ${dependency}`);
    const declaration = input.declaration === undefined ? undefined : (() => {
      const declarationPath = resolve(SOURCE_ROOT, "../declarations", input.declaration);
      if (!declarationPath.startsWith(`${resolve(SOURCE_ROOT, "../declarations")}/`) || !existsSync(declarationPath)) throw new Error(`missing stdlib declaration: ${input.declaration}`);
      const declarationSource = normalize(readFileSync(declarationPath, "utf8"));
      const declarationAsset = `declarations/${input.declaration}`;
      const reference = { path: declarationAsset, sha256: sha256(declarationSource) };
      writeText(temp, declarationAsset, declarationSource);
      files.push(reference);
      return reference;
    })();

    entries.push({
      specifier: input.specifier,
      visibility: input.visibility,
      source: sourceReference,
      ...(declaration === undefined ? {} : { declaration }),
      dependencies,
      host_primitives: input.hostPrimitives.map(primitive => ({
        name: primitive.name,
        abi_version: primitive.abiVersion,
        methods: [...primitive.methods],
      })),
    });
  }

  entries.sort((left, right) => left.specifier.localeCompare(right.specifier));
  const hostPrimitiveCatalog = [...new Map(entries.flatMap(entry => entry.host_primitives).map(primitive => [primitive.name, primitive])).values()]
    .sort((left, right) => left.name.localeCompare(right.name));
  const embedded = [
    "// @generated by tools/effect-assets/scripts/generate-stdlib.ts; do not edit.",
    "/// Blitz stdlib source and declaration assets for the future prelinked graph.",
    `pub const BLITZ_STDLIB_EFFECT_VERSION: &str = ${JSON.stringify(EFFECT_VERSION)};`,
    `pub const BLITZ_STDLIB_RUNTIME_ABI_VERSION: u16 = ${RUNTIME_ABI_VERSION};`,
    `pub const BLITZ_STDLIB_HOST_ABI_VERSION: u16 = ${HOST_ABI_VERSION};`,
    "",
    "pub struct EmbeddedHostPrimitive {",
    "  pub name: &'static str,",
    "  pub abi_version: u16,",
    "  pub methods: &'static [&'static str],",
    "}",
    "",
    "pub struct EmbeddedBlitzStdlibModule {",
    "  pub specifier: &'static str,",
    "  pub source: &'static str,",
    "  pub declaration: Option<&'static str>,",
    "  pub source_sha256: &'static str,",
    "  pub declaration_sha256: Option<&'static str>,",
    "  pub visibility: &'static str,",
    "  pub dependencies: &'static [&'static str],",
    "  pub host_primitives: &'static [EmbeddedHostPrimitive],",
    "}",
    "",
    "pub const EMBEDDED_BLITZ_STDLIB_MODULES: &[EmbeddedBlitzStdlibModule] = &[",
    ...entries.map(entry => [
      "  EmbeddedBlitzStdlibModule {",
      `    specifier: ${JSON.stringify(entry.specifier)},`,
      `    source: include_str!(${JSON.stringify(entry.source.path)}),`,
      `    declaration: ${entry.declaration === undefined ? "None" : `Some(include_str!(${JSON.stringify(entry.declaration.path)}))`},`,
      `    source_sha256: ${JSON.stringify(entry.source.sha256)},`,
      `    declaration_sha256: ${entry.declaration === undefined ? "None" : `Some(${JSON.stringify(entry.declaration.sha256)})`},`,
      `    visibility: ${JSON.stringify(entry.visibility)},`,
      `    dependencies: &[${entry.dependencies.map(value => JSON.stringify(value)).join(", ")}],`,
      `    host_primitives: &[${entry.host_primitives.map(primitive => `EmbeddedHostPrimitive { name: ${JSON.stringify(primitive.name)}, abi_version: ${primitive.abi_version}, methods: &[${primitive.methods.map(method => JSON.stringify(method)).join(", ")}] }`).join(", ")}],`,
      "  },",
    ].join("\n")),
    "];",
    "",
  ].join("\n");
  writeText(temp, "embedded.rs", embedded);
  files.push({ path: "embedded.rs", sha256: sha256(embedded) });
  files.sort((left, right) => left.path.localeCompare(right.path));

  const manifest: StdlibManifest = {
    format: STDLIB_FORMAT_VERSION,
    package: {
      name: "blitz-stdlib",
      version: STDLIB_VERSION,
      effect_version: EFFECT_VERSION,
      runtime_abi_version: RUNTIME_ABI_VERSION,
      host_abi_version: HOST_ABI_VERSION,
    },
    host_primitive_catalog: hostPrimitiveCatalog,
    entries,
    files,
  };
  writeText(temp, "manifest.json", `${JSON.stringify(manifest, null, 2)}\n`);

  const old = `${OUTPUT}.old-${process.pid}`;
  rmSync(old, { recursive: true, force: true });
  if (existsSync(OUTPUT)) renameSync(OUTPUT, old);
  try {
    renameSync(temp, OUTPUT);
    rmSync(old, { recursive: true, force: true });
  } catch (error) {
    if (existsSync(OUTPUT)) rmSync(OUTPUT, { recursive: true, force: true });
    if (existsSync(old)) renameSync(old, OUTPUT);
    throw error;
  }
  const bytes = files.reduce((sum, file) => sum + statSync(join(OUTPUT, file.path)).size, 0);
  console.log(`Generated ${entries.length} Blitz stdlib entries (${files.length} hashed files, ${bytes} bytes) at ${relative(resolve(import.meta.dirname, "../.."), OUTPUT)}`);
};

main();
